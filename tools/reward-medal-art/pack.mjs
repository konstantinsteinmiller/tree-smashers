#!/usr/bin/env node
/**
 * Painted reward-reveal medallion (gold ring on an 8-point sunburst) → one
 * keyed WebP + the generated registry RewardRevealHost.vue reads.
 *
 *   node tools/reward-medal-art/pack.mjs [--in art-sheets/painted/reward-medal.png] [--q 0.88]
 *
 * Key: tools/art-desk/slice.mjs (magenta → alpha everywhere, incl. the round
 *      centre hole) at native size, then trimmed to the medallion's content.
 * Hole: the transparent region 4-connected to the clear pixel nearest the
 *      content centre (searched in the middle third), measured as its bbox →
 *      centre + diameter as fractions of the box. A hole that is not round
 *      (bbox aspect off by > 12 %) or leaks to the box edge is reported
 *      `NOT_A_HOLE` and nothing ships (exit 3).
 * Out: public/images/reward-medal/medal_<W>x<H>.webp — the hole is laid over
 *      the prize plate, so the box is plate ÷ holeD wide; width for the
 *      biggest plate (.is-big: 11.5rem = 184 css px) ÷ holeD at 3× DPR, never
 *      upscaled; src/use/paintedRewardMedal.ts.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openCanvas } from '../art-desk/imaging.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const arg = (k, d) => { const i = a.indexOf(k); return i >= 0 ? a[i + 1] : d }
const Q = Number(arg('--q', '0.88'))
const SRC = resolve(ROOT, arg('--in', join('art-sheets', 'painted', 'reward-medal.png')))
const OUT = join(ROOT, 'public', 'images', 'reward-medal')
const REG = join(ROOT, 'src', 'use', 'paintedRewardMedal.ts')
const MAX_PLATE_PX = 11.5 * 16 * 3

const writeReg = (p) => writeFileSync(REG, `// GENERATED by tools/reward-medal-art/pack.mjs — do not edit by hand.
// The painted reward-reveal medallion in public/images/reward-medal/.
// holeX/holeY: opening centre as a fraction of the box; holeD: opening
// diameter as a fraction of the box WIDTH; aspect = w / h.
// null = the CSS star + ring stay (src/components/organisms/RewardRevealHost.vue).
export interface PaintedRewardMedal {
  file: string
  w: number
  h: number
  aspect: number
  holeX: number
  holeY: number
  holeD: number
  v: string
}
export const PAINTED_REWARD_MEDAL: PaintedRewardMedal | null = ${p
  ? `{\n  file: '${p.file}',\n  w: ${p.w},\n  h: ${p.h},\n  aspect: ${p.aspect},\n  holeX: ${p.holeX},\n  holeY: ${p.holeY},\n  holeD: ${p.holeD},\n  v: '${p.v}'\n}`
  : 'null'}
`)

if (!existsSync(SRC)) { console.error('not painted yet'); writeReg(null); process.exit(0) }
const tmp = join(tmpdir(), `reward-medal-pack-${process.pid}`)
mkdirSync(tmp, { recursive: true })
const head = readFileSync(SRC)
const W0 = head.readUInt32BE(16), H0 = head.readUInt32BE(20)
const k = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'), '--in', SRC, '--out-dir', tmp,
  '--size', `${W0}x${H0}`, '--fit', 'cell', '--png', '--quality', '1', '--names', 'medal'],
{ cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
if (k.status !== 0) { console.error('key failed'); process.exit(1) }

const { page, close } = await openCanvas(ROOT)
let r
try {
  r = await page.evaluate(async ({ b64, MAX_PLATE_PX, Q }) => {
    const bin = Uint8Array.from(atob(b64), c => c.charCodeAt(0))
    const bmp = await createImageBitmap(new Blob([bin], { type: 'image/png' }), { premultiplyAlpha: 'none', colorSpaceConversion: 'none' })
    const W0 = bmp.width, H0 = bmp.height
    const c0 = new OffscreenCanvas(W0, H0)
    c0.getContext('2d').drawImage(bmp, 0, 0)
    const d0 = c0.getContext('2d').getImageData(0, 0, W0, H0).data
    let L = W0, R = -1, T = H0, B = -1
    for (let y = 0; y < H0; y++) for (let x = 0; x < W0; x++) {
      if (d0[(y * W0 + x) * 4 + 3] > 40) { if (x < L) L = x; if (x > R) R = x; if (y < T) T = y; if (y > B) B = y }
    }
    if (R < 0) return { ok: false, why: 'EMPTY' }
    const pad = 2
    L = Math.max(0, L - pad); T = Math.max(0, T - pad); R = Math.min(W0 - 1, R + pad); B = Math.min(H0 - 1, B + pad)
    const W = R - L + 1, H = B - T + 1
    const c1 = new OffscreenCanvas(W, H)
    c1.getContext('2d').drawImage(c0, L, T, W, H, 0, 0, W, H)
    const d = c1.getContext('2d').getImageData(0, 0, W, H).data
    const clear = (x, y) => d[(y * W + x) * 4 + 3] < 128
    let seed = null, best = Infinity
    for (let y = (H / 3) | 0; y < (2 * H / 3) | 0; y++) for (let x = (W / 3) | 0; x < (2 * W / 3) | 0; x++) {
      if (!clear(x, y)) continue
      const dd = (x - W / 2) ** 2 + (y - H / 2) ** 2
      if (dd < best) { best = dd; seed = [x, y] }
    }
    if (!seed) return { ok: false, why: 'NOT_A_HOLE: no clear pixel in the middle third' }
    const seen = new Uint8Array(W * H), st = [seed[1] * W + seed[0]]
    seen[st[0]] = 1
    let hl = W, hr = -1, ht = H, hb = -1, n = 0
    while (st.length) {
      const p = st.pop(), x = p % W, y = (p / W) | 0
      n++
      if (x < hl) hl = x; if (x > hr) hr = x; if (y < ht) ht = y; if (y > hb) hb = y
      for (const [nx, ny] of [[x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]]) {
        if (nx < 0 || ny < 0 || nx >= W || ny >= H) continue
        const q = ny * W + nx
        if (!seen[q] && clear(nx, ny)) { seen[q] = 1; st.push(q) }
      }
    }
    const hw = hr - hl + 1, hh = hb - ht + 1
    if (hl <= 0 || ht <= 0 || hr >= W - 1 || hb >= H - 1) return { ok: false, why: 'NOT_A_HOLE: the clear region leaks to the edge' }
    if (Math.abs(hw / hh - 1) > 0.12) return { ok: false, why: `NOT_A_HOLE: ${hw}x${hh}` }
    const fill = n / (Math.PI * (hw / 2) * (hh / 2))
    const holeDW = ((hw + hh) / 2) / W
    const w = Math.min(W, Math.ceil(MAX_PLATE_PX / holeDW)), s = w / W, h = Math.round(H * s)
    const c2 = new OffscreenCanvas(w, h), g = c2.getContext('2d')
    g.imageSmoothingQuality = 'high'
    g.drawImage(c1, 0, 0, W, H, 0, 0, w, h)
    const u = new Uint8Array(await (await c2.convertToBlob({ type: 'image/webp', quality: Q })).arrayBuffer())
    let bs = ''
    for (let i = 0; i < u.length; i += 0x8000) bs += String.fromCharCode(...u.subarray(i, i + 0x8000))
    return {
      ok: true, w, h, b64: btoa(bs), src: { W, H, hole: [hl, ht, hw, hh], fill: +fill.toFixed(3) },
      holeX: +(((hl + hr + 1) / 2) / W).toFixed(4),
      holeY: +(((ht + hb + 1) / 2) / H).toFixed(4),
      holeD: +(((hw + hh) / 2) / W).toFixed(4)
    }
  }, { b64: readFileSync(join(tmp, 'medal.png')).toString('base64'), MAX_PLATE_PX, Q })
} finally {
  await close()
  rmSync(tmp, { recursive: true, force: true })
}
if (!r.ok) { console.log(r.why); process.exit(3) }
mkdirSync(OUT, { recursive: true })
for (const f of readdirSync(OUT)) if (f.startsWith('medal_')) rmSync(join(OUT, f))
const file = `medal_${r.w}x${r.h}.webp`
writeFileSync(join(OUT, file), Buffer.from(r.b64, 'base64'))
const v = createHash('sha1').update(r.b64).digest('hex').slice(0, 8)
writeReg({ file, w: r.w, h: r.h, aspect: +(r.w / r.h).toFixed(4), holeX: r.holeX, holeY: r.holeY, holeD: r.holeD, v })
console.error(`src ${JSON.stringify(r.src)} → ${file} hole ${r.holeX},${r.holeY} d ${r.holeD}`)
console.log(`${join(OUT, file)} (${Math.round(Buffer.from(r.b64, 'base64').length / 1024)} kB)`)
