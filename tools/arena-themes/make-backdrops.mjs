#!/usr/bin/env node
/**
 * Painted theme backdrops → seamless runtime tiles + registry.
 *
 *   node tools/arena-themes/make-backdrops.mjs [--size 768] [--only <theme,...>]
 *
 * In:  art-sheets/painted/backdrop-<theme>.png (meadow: backdrop-highland.png)
 *      — prompts in art-sheets/bg/<theme>.prompt.txt (tools/arena-themes/prompts.mjs).
 * Out: public/images/bg/<theme>-tile_<s>x<s>.webp (meadow keeps
 *      highland-tile_768x768.webp), seamless via tools/bg-tile/make-tile.mjs
 *      --hard (flat cel tones keep hard edges in the seam band);
 *      src/use/paintedBackdrops.ts — generated registry.
 * The tile is drawn at most `units` arena units wide and never upscaled
 * (arenaBackdrop.ts): 768 px / 230 units = 3.3 device px per unit, above a
 * 3× phone (≈2.5) and a 1080p desktop (≈2.3).
 */
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const opt = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d }
const SIZE = +opt('size', 768)
const only = opt('only', null)?.split(',')
const UNITS = 230
const THEMES = ['meadow', 'woodland', 'rocky', 'snowy', 'volcanic', 'ruins', 'bedroom']
const src = t => join(ROOT, 'art-sheets', 'painted', t === 'meadow' ? 'backdrop-highland.png' : `backdrop-${t}.png`)
const out = t => `${t === 'meadow' ? 'highland' : t}-tile_${SIZE}x${SIZE}.webp`

const reg = {}
for (const t of THEMES) {
  if (!existsSync(src(t)) && t !== 'bedroom') continue
  const file = out(t)
  const dest = join(ROOT, 'public', 'images', 'bg', file)
  if (!only || only.includes(t) || !existsSync(dest)) {
    // Structured, periodic floors (planks) cannot be cross-faded without ghost blobs: the
    // bedroom tile is DRAWN, seamless by construction (tools/bg-tile/make-planks.mjs).
    const r = t === 'bedroom'
      ? spawnSync(process.execPath, [join(ROOT, 'tools', 'bg-tile', 'make-planks.mjs'), dest, '--size', String(SIZE)], { stdio: 'inherit' })
      : spawnSync(process.execPath, [join(ROOT, 'tools', 'bg-tile', 'make-tile.mjs'), src(t), dest, '--size', String(SIZE), '--hard'], { stdio: 'inherit' })
    if (r.status !== 0) { console.error(`${t}: make-tile failed`); process.exit(1) }
    // the 2 × 2 seam check belongs with the art, not in public/
    if (existsSync(`${dest}.preview.png`)) renameSync(`${dest}.preview.png`, join(ROOT, 'art-sheets', 'bg', `${t}-tile.preview.png`))
  }
  const buf = readFileSync(dest)
  reg[t] = { file, size: SIZE, units: UNITS, v: createHash('sha1').update(buf).digest('hex').slice(0, 8) }
  console.log(`${t}: ${file} ${(buf.length / 1024).toFixed(1)} kB`)
}
const rows = Object.entries(reg).map(([t, r]) => `  ${t}: { file: ${JSON.stringify(r.file)}, size: ${r.size}, units: ${r.units}, v: '${r.v}' }`)
writeFileSync(join(ROOT, 'src', 'use', 'paintedBackdrops.ts'), `// GENERATED by tools/arena-themes/make-backdrops.mjs — do not edit by hand.
// Painted, seamless backdrop tiles per arena theme in public/images/bg/.
// \`units\` = the most arena units one tile spans (fewer where that would
// upscale it — arenaBackdrop.ts).
import type { ArenaTheme } from '@/use/arenaThemes'
export const PAINTED_BACKDROPS: Readonly<Partial<Record<ArenaTheme, { file: string, size: number, units: number, v: string }>>> = {
${rows.join(',\n')}
}
`)
