#!/usr/bin/env node
/**
 * Painted UI icons → 128 + 256 px WebP + the generated registry.
 *
 *   node tools/ui-icons/pack.mjs [--q 0.82]
 *
 * In:  art-sheets/painted/ui-icon-<name>.png (one icon on flat magenta, from
 *      paint-queue.mjs; prompts in art-sheets/ui-icons/).
 * Out: public/images/ui-icons/<name>_128x128.webp + <name>_256x256.webp —
 *      magenta keyed to alpha, trimmed, centred with a 4% margin (the
 *      Art Desk slicer, tools/art-desk/slice.mjs: ground colour measured on the
 *      frame edge, 2 px despill); src/use/paintedUiIcons.ts — the registry
 *      UiIcon.vue reads. An icon with no painting stays OUT of the registry, so
 *      the drawn SVG is used for it.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ICONS, STAT_ICONS } from './prompts.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const Q = (() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.82' })()
const OUT = join(ROOT, 'public', 'images', 'ui-icons')
const REG = join(ROOT, 'src', 'use', 'paintedUiIcons.ts')
mkdirSync(OUT, { recursive: true })

const entries = []
for (const name of Object.keys(ICONS)) {
  const src = join(ROOT, 'art-sheets', 'painted', `ui-icon-${name}.png`)
  if (!existsSync(src)) { console.error(`${name}: not painted yet — drawn SVG stays`); continue }
  const files = {}
  // Stat icons show at 14–24 css px (battle stat cards, team modal rows):
  // 64 px for 1×, 128 for 2–3×, 256 for the canvas stamps (power-up box plate,
  // the floating pick-up label) — every use downsamples, none upscales.
  const sizes = STAT_ICONS.includes(name) ? [64, 128, 256] : [128, 256]
  for (const px of sizes) {
    const base = `${name}_${px}x${px}`
    const r = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'),
      '--in', src, '--out-dir', OUT, '--size', `${px}x${px}`, '--fit', 'trim', '--pad', '0.04', '--quality', Q, '--names', base],
    { cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
    if (r.status !== 0) { console.error(`${name}: slice ${px} failed (exit ${r.status}) — drawn SVG stays`); break }
    files[px] = `${base}.webp`
  }
  if (!sizes.every(px => files[px])) continue
  const h = createHash('sha1')
  for (const px of sizes) h.update(readFileSync(join(OUT, files[px])))
  const v = h.digest('hex').slice(0, 8)
  const [f1, f2, f4] = sizes.map(px => files[px])
  entries.push(`  '${name}': { file: '${f1}', file2x: '${f2}'${f4 ? `, file4x: '${f4}'` : ''}, v: '${v}' }`)
  console.error(`${name}: ok (${v})`)
}

writeFileSync(REG, `// GENERATED by tools/ui-icons/pack.mjs — do not edit by hand.
// Painted UI icons in public/images/ui-icons/ (128 px \`file\`, 256 px \`file2x\`;
// stat icons: 64 / 128 / 256 px \`file\` / \`file2x\` / \`file4x\`).
// A missing entry falls back to the drawn SVG (src/components/icons/UiIcon.vue).
export type UiIconName = ${Object.keys(ICONS).map(n => `'${n}'`).join(' | ')}
export interface PaintedUiIcon { file: string, file2x: string, file4x?: string, v: string }
export const PAINTED_UI_ICONS: Readonly<Partial<Record<UiIconName, PaintedUiIcon>>> = {${entries.length ? `\n${entries.join(',\n')}\n` : ''}}
`)
console.log(`${REG} (${entries.length} painted)`)
