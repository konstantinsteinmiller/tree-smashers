#!/usr/bin/env node
/**
 * Painted floor decor → one small atlas + src/use/paintedDecor.ts.
 *
 *   node tools/decor-sheets/pack.mjs [--q 0.84]
 *
 * In:  art-sheets/painted/decor-sheet.png (4 × 4, prompts.mjs CELLS order).
 * Out: public/images/terrain/decor_384x384.webp — 4 × 4 cells of 96 px, each
 *      sprite keyed, trimmed and fitted inside 92 px, centred in its cell;
 *      registry rects [x, y, w, h] per sprite. Size: a decor sprite is drawn
 *      ≤ 11 arena units across; 92 px covers ~8.4 device px / unit (a 4K
 *      desktop bake at 2×) — above that the vector drawing is used. Never
 *      upscaled (a ~1024 px painting gives ~140 px of content per sprite).
 *      An empty cell, or a sprite touching its cell edge (spilled into a
 *      neighbour), REFUSES the whole sheet: the registry is written null and
 *      the vector decor stays.
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { openCanvas } from '../art-desk/imaging.mjs'
import { PAINTED, ROOT, keyCells, trimCells } from '../sprite-pack/lib.mjs'
import { CELLS } from './prompts.mjs'

const a = process.argv.slice(2)
const Q = Number((() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.84' })())
const OUT = join(ROOT, 'public', 'images', 'terrain')
const REG = join(ROOT, 'src', 'use', 'paintedDecor.ts')
const CELL = 96
const FIT = 92
const names = CELLS.map(([n]) => n)

const writeReg = (meta) => writeFileSync(REG, `// GENERATED by tools/decor-sheets/pack.mjs — do not edit by hand.
// Painted floor decor atlas in public/images/terrain/: one sprite per name,
// rect [x, y, w, h] in atlas pixels (each centred in a ${CELL} px cell). null =
// not painted / refused → the vector DECOR_DRAW stays (arenaDecorArt.ts).
export const PAINTED_DECOR_NAMES = ${JSON.stringify(names)} as const
export type DecorSpriteName = typeof PAINTED_DECOR_NAMES[number]
export interface PaintedDecor { file: string, v: string, rects: Readonly<Record<DecorSpriteName, readonly [number, number, number, number]>> }
export const PAINTED_DECOR: PaintedDecor | null = ${meta ? JSON.stringify(meta, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'") : 'null'}
`)

for (const f of existsSync(OUT) ? readdirSync(OUT) : []) if (f.startsWith('decor_')) rmSync(join(OUT, f))
const SRC = join(PAINTED, 'decor-sheet.png')
if (!existsSync(SRC)) { console.error('not painted yet — vector decor stays'); writeReg(null); console.log(REG); process.exit(0) }
const k = keyCells(SRC, 4, 4, names)
const { page, close } = await openCanvas(ROOT)
let out
try {
  const res = await trimCells(page, names.map(n => ({ name: n, png: k.cells[n], maxW: FIT, maxH: FIT, pad: 1 })), Q)
  const bad = names.filter(n => !res[n].ok).map(n => `${n}: ${res[n].why}`)
  if (bad.length) { console.error(`REFUSED — ${bad.join('; ')}`); writeReg(null); process.exit(3) }
  out = await page.evaluate(async ({ cells, CELL, Q }) => {
    const atlas = new OffscreenCanvas(CELL * 4, CELL * 4)
    const g = atlas.getContext('2d')
    const rects = {}
    for (let i = 0; i < cells.length; i++) {
      const { name, png, w, h } = cells[i]
      const bin = Uint8Array.from(atob(png), c => c.charCodeAt(0))
      const bmp = await createImageBitmap(new Blob([bin], { type: 'image/png' }))
      const x = (i % 4) * CELL + Math.round((CELL - w) / 2)
      const y = Math.floor(i / 4) * CELL + Math.round((CELL - h) / 2)
      g.drawImage(bmp, x, y)
      rects[name] = [x, y, w, h]
    }
    const u = new Uint8Array(await (await atlas.convertToBlob({ type: 'image/webp', quality: Q })).arrayBuffer())
    let bs = ''
    for (let i = 0; i < u.length; i += 0x8000) bs += String.fromCharCode(...u.subarray(i, i + 0x8000))
    return { b64: btoa(bs), rects }
  }, { cells: names.map(n => ({ name: n, png: res[n].png, w: res[n].w, h: res[n].h })), CELL, Q })
} finally {
  await close()
  rmSync(k.tmp, { recursive: true, force: true })
}
mkdirSync(OUT, { recursive: true })
const file = `decor_${CELL * 4}x${CELL * 4}.webp`
const buf = Buffer.from(out.b64, 'base64')
writeFileSync(join(OUT, file), buf)
writeReg({ file, v: createHash('sha1').update(buf).digest('hex').slice(0, 8), rects: out.rects })
console.error(`${file} ${Math.round(buf.length / 1024)} kB`)
console.log(REG)
