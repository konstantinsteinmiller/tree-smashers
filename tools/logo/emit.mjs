/**
 * Writes what the game reads about the logo, from tools/logo/layout.json
 * (build.mjs) and tools/logo/painted.json (pack.mjs, optional):
 *
 *   src/data/logoArt.ts  — the registry: each lockup part's SVG, its painted
 *                          version (if any) and the `srcset` / `sizes` pair
 *                          that lets the browser pick the painting only where
 *                          its pixels cover css width × DPR (else the SVG).
 *   index.html           — the #static-splash logo markup between
 *                          <!-- logo:start --> / <!-- logo:end --> and the
 *                          part boxes between /* logo-layout:start *\/ and
 *                          /* logo-layout:end *\/ in the shared loader CSS.
 *
 * The splash and FLogoProgress.vue render the same parts with the same
 * classes and the same CSS (index.html's <style> is the one source), so the
 * hand-over shows the same frame.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const PARTS = ['emblem', 'tree', 'smashers']
/** The svg is effectively unlimited: declare it far above any painting. */
const SVG_W = 4096

export function emit (ROOT) {
  const layout = JSON.parse(readFileSync(join(ROOT, 'tools', 'logo', 'layout.json'), 'utf8'))
  const paintedPath = join(ROOT, 'tools', 'logo', 'painted.json')
  const painted = existsSync(paintedPath) ? JSON.parse(readFileSync(paintedPath, 'utf8')) : null

  // css width of the whole lockup (= `.ts-card`, written into index.html below)
  const LOCKUP_CSS = `min(84vw, ${layout.maxCssWidth}px, ${(layout.heightShare * 100).toFixed(0)}vh * ${layout.aspect.toFixed(4)})`
  const parts = {}
  for (const name of PARTS) {
    const box = layout.boxes[name]
    const svg = `images/logo/${layout.files[name]}?v=${layout.v}`
    const p = painted?.parts?.[name] ?? null
    const sizes = `calc(${LOCKUP_CSS} * ${(box.w / 100).toFixed(4)})`
    const srcset = p ? `images/logo/${p.file}?v=${painted.v} ${p.w}w, ${svg} ${SVG_W}w` : ''
    parts[name] = { svg, painted: p ? { file: `images/logo/${p.file}?v=${painted.v}`, w: p.w, h: p.h } : null, srcset, sizes: p ? sizes : '' }
  }

  // ── registry ──
  const ts = `// GENERATED by tools/logo/build.mjs (+ tools/logo/pack.mjs for the painted
// parts) — do not edit by hand. The Tree Smashers logo lockup: three parts in
// one box. index.html carries the part boxes (/* logo-layout */) in the loader
// CSS that #static-splash and FLogoProgress.vue share, so both draw the same
// frame. Paths are relative to the public dir (prependBaseUrl them).
// \`painted\` is the Art Desk version of a part; \`srcset\` + \`sizes\` let the
// browser use it only where its pixels cover the part's css width × DPR and
// fall back to the SVG (declared ${SVG_W}w) everywhere else.
export type LogoPartName = 'emblem' | 'tree' | 'smashers'
export interface LogoPart {
  svg: string
  painted: { file: string, w: number, h: number } | null
  srcset: string
  sizes: string
}
export const LOGO_VERSION = '${painted ? painted.v : layout.v}'
export const LOGO_PAINTED = ${painted ? 'true' : 'false'}
export const LOGO_PARTS: Readonly<Record<LogoPartName, LogoPart>> = ${JSON.stringify(parts, null, 2).replace(/"([a-z]+)":/g, '$1:').replace(/"/g, '\'')}
/** The emblem alone (HUD logo, loader runner): always the crisp SVG. */
export const LOGO_EMBLEM_SVG = '${parts.emblem.svg}'
/** The emblem's width / height (its HUD box keeps the same shape). */
export const LOGO_EMBLEM_ASPECT = ${layout.emblemAspect.toFixed(4)}
/** Mini disc (favicon art) — the loader bar's runner. */
export const LOGO_DISC_SVG = 'favicon.svg?v=${layout.v}'
`
  writeFileSync(join(ROOT, 'src', 'data', 'logoArt.ts'), ts)

  // ── index.html ──
  const htmlPath = join(ROOT, 'index.html')
  let html = readFileSync(htmlPath, 'utf8')
  const img = (name, cls) => {
    const p = parts[name]
    const src = `/${p.svg}`
    const set = p.srcset ? ` srcset="${p.srcset.split(', ').map((s) => `/${s}`).join(', ')}" sizes="${p.sizes}"` : ''
    return `<img class="${cls}" src="${src}"${set} alt="" draggable="false">`
  }
  const disc = `/favicon.svg?v=${layout.v}`
  const markup = [
    '<!-- logo:start — generated by tools/logo/build.mjs; FLogoProgress.vue renders the same tree -->',
    '      <div class="ts-logo">',
    `        <div class="ts-logo__part ts-logo__emblem"><div class="ts-logo__fly"><div class="ts-logo__anim ts-logo__anim--emblem">${img('emblem', 'ts-logo__img')}</div></div></div>`,
    `        <div class="ts-logo__part ts-logo__tree"><div class="ts-logo__anim ts-logo__anim--tree">${img('tree', 'ts-logo__img')}</div></div>`,
    `        <div class="ts-logo__part ts-logo__smashers"><div class="ts-logo__anim ts-logo__anim--smashers">${img('smashers', 'ts-logo__img')}<div class="ts-logo__shine"></div></div></div>`,
    '      </div>',
    '      <div class="ts-meter">',
    '        <div class="ts-bar">',
    '          <div class="ts-bar__track"><div class="ts-bar__fill"></div><div class="ts-bar__notches"></div></div>',
    `          <div class="ts-bar__run"><div class="ts-bar__disc"><img src="${disc}" alt="" draggable="false"></div></div>`,
    '        </div>',
    '        <div class="ts-pct"></div>',
    '      </div>',
    '      <div class="ts-tip"></div>',
    '      <!-- logo:end -->'
  ].join('\n')
  html = replaceBetween(html, '<!-- logo:start', '<!-- logo:end -->', markup)
  const b = layout.boxes
  const box = (n) => `left: ${b[n].x.toFixed(3)}%; top: ${b[n].y.toFixed(3)}%; width: ${b[n].w.toFixed(3)}%; height: ${b[n].h.toFixed(3)}%;`
  const css = [
    '/* logo-layout:start — generated by tools/logo/build.mjs */',
    `      .ts-card { width: ${LOCKUP_CSS}; }`,
    `      .ts-logo { aspect-ratio: ${layout.W} / ${layout.H}; }`,
    `      .ts-logo__emblem { ${box('emblem')} }`,
    `      .ts-logo__tree { ${box('tree')} }`,
    `      .ts-logo__smashers { ${box('smashers')} }`,
    `      .ts-logo__shine { -webkit-mask-image: url('/${parts.smashers.svg}'); mask-image: url('/${parts.smashers.svg}');${painted ? ' display: none;' : ''} }`,
    '      /* logo-layout:end */'
  ].join('\n')
  html = replaceBetween(html, '/* logo-layout:start', '/* logo-layout:end */', css)
  writeFileSync(htmlPath, html)
  return { parts, layout, painted }
}

function replaceBetween (src, startTok, endTok, replacement) {
  const a = src.indexOf(startTok)
  const e = src.indexOf(endTok)
  if (a < 0 || e < 0 || e < a) throw new Error(`index.html: markers ${startTok} … ${endTok} not found`)
  return src.slice(0, a) + replacement + src.slice(e + endTok.length)
}
