#!/usr/bin/env node
/**
 * Painted boss badges / level-up arrow / movie icon → WebP + the registry.
 *
 *   node tools/badge-icons/pack.mjs [--q 0.84]
 *
 * In:  art-sheets/painted/badge-<name>.png (one icon on flat magenta).
 * Out: public/images/<dir>/painted-<name>_<W>x<H>.webp — keyed, trimmed and
 *      centred with a 4 % margin by tools/art-desk/slice.mjs (measured ground,
 *      despill). Sizes = the largest display × 3 DPR, from paintings of
 *      ~1024 px, so nothing is upscaled:
 *        boss badges 256 (crest ≤ 84 css px: intro card / next-boss peek),
 *        level-up 256 (same file the old stat sheet shipped),
 *        movie 128 × 96 (≤ 40 css px wide on the rewarded-ad CTAs; same box
 *        as the old file, so no CTA layout moves).
 *      src/use/paintedBadgeIcons.ts — an icon with no painting stays OUT, so
 *      its old file is used (src/use/badgeIconArt.ts).
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { PAINTED, ROOT } from '../sprite-pack/lib.mjs'
import { ICONS } from './prompts.mjs'

const a = process.argv.slice(2)
const Q = (() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.84' })()
const REG = join(ROOT, 'src', 'use', 'paintedBadgeIcons.ts')
// The boss badges live in their OWN module: the generic registry sits in the main bundle, and a
// boss-free build must not carry the boss badge paths (tests/platforms/bosses100FlagPurity).
const REG_BOSS = join(ROOT, 'src', 'use', 'paintedBossBadges.ts')

const entries = []
const bossEntries = []
for (const [name, { size: [w, h], file: dir }] of Object.entries(ICONS)) {
  const OUT = join(ROOT, 'public', 'images', dir)
  for (const f of existsSync(OUT) ? readdirSync(OUT) : []) if (f.startsWith(`painted-${name}_`)) rmSync(join(OUT, f))
  const src = join(PAINTED, `badge-${name}.png`)
  if (!existsSync(src)) { console.error(`${name}: not painted yet — old file stays`); continue }
  mkdirSync(OUT, { recursive: true })
  const base = `painted-${name}_${w}x${h}`
  const r = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'),
    '--in', src, '--out-dir', OUT, '--size', `${w}x${h}`, '--fit', 'trim', '--pad', '0.04', '--quality', Q, '--names', base],
  { cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
  if (r.status !== 0) { console.error(`${name}: slice failed (exit ${r.status}) — old file stays`); continue }
  const v = createHash('sha1').update(readFileSync(join(OUT, `${base}.webp`))).digest('hex').slice(0, 8)
  ;(name.startsWith('boss-') ? bossEntries : entries).push(`  '${name}': { file: 'images/${dir}/${base}.webp', v: '${v}' }`)
  console.error(`${name}: ok (${v})`)
}

writeFileSync(REG, `// GENERATED by tools/badge-icons/pack.mjs — do not edit by hand.
// Toy-box repaints of the level-up arrow and the movie icon (the boss badges are in
// paintedBossBadges.ts). Paths under public/. A missing entry keeps the old file (badgeIconArt.ts).
export type BadgeIconName = ${Object.keys(ICONS).map(n => `'${n}'`).join(' | ')}
export const PAINTED_BADGE_ICONS: Readonly<Partial<Record<BadgeIconName, { file: string, v: string }>>> = {${entries.length ? `\n${entries.join(',\n')}\n` : ''}}
`)
writeFileSync(REG_BOSS, `// GENERATED by tools/badge-icons/pack.mjs — do not edit by hand.
// Toy-box repaints of the boss badges (paths under public/); read only by data/bossArt.ts.
import type { BadgeIconName } from '@/use/paintedBadgeIcons'
export const PAINTED_BOSS_BADGES: Readonly<Partial<Record<BadgeIconName, { file: string, v: string }>>> = {${bossEntries.length ? `\n${bossEntries.join(',\n')}\n` : ''}}
`)
console.log(`${REG} (${entries.length} painted), ${REG_BOSS} (${bossEntries.length} painted)`)
