#!/usr/bin/env node
/**
 * Painted reveal gift → two WebP sprites (lid + box body) + the generated registry.
 *
 *   node tools/gift-art/pack.mjs [--q 0.85]
 *
 * In:  art-sheets/painted/reveal-gift.png (paint-queue.mjs): the lid on top, the
 *      body below, on flat magenta.
 * Cut: the ground is measured on the frame edge; the widest empty row band in the
 *      middle 20–80% of the height splits the parts. No clean band → exit 3
 *      (the queue repaints). Each part is cropped to its own content.
 * Out: public/images/reveal-gift/{lid,box}_<W>x<H>.webp — magenta keyed to alpha
 *      by the Art Desk slicer (tools/art-desk/slice.mjs), at the part's own aspect
 *      and its on-screen size at 3× DPR (the gift is at most 11rem = 176 css px
 *      wide: body 88% → 464 px, lid 96% → 507 px), never upscaled;
 *      src/use/paintedRevealGift.ts — the registry RewardRevealHost.vue reads
 *      (null = the CSS gift stays).
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openCanvas } from '../art-desk/imaging.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const Q = (() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.85' })()
const SRC = join(ROOT, 'art-sheets', 'painted', 'reveal-gift.png')
const OUT = join(ROOT, 'public', 'images', 'reveal-gift')
const REG = join(ROOT, 'src', 'use', 'paintedRevealGift.ts')
/** Max on-screen width at 3× DPR, per part (css: 176 px gift × share × 3). */
const MAX_W = { lid: 507, box: 464 }

const writeReg = (body) => writeFileSync(REG, `// GENERATED by tools/gift-art/pack.mjs — do not edit by hand.
// The painted reward-reveal gift in public/images/reveal-gift/: the lid (with its
// bow) and the box body, cut from one painting. null = the CSS gift is drawn
// (src/components/organisms/RewardRevealHost.vue).
export interface GiftPart { file: string, w: number, h: number }
export interface PaintedRevealGift { lid: GiftPart, box: GiftPart, v: string }
export const PAINTED_REVEAL_GIFT: PaintedRevealGift | null = ${body}
`)

if (!existsSync(SRC)) { writeReg('null'); console.log('not painted yet — CSS gift stays'); process.exit(0) }

const { page, close } = await openCanvas(ROOT)
let cut
try {
  cut = await page.evaluate(async (b64) => {
    const bin = Uint8Array.from(atob(b64), c => c.charCodeAt(0))
    const bmp = await createImageBitmap(new Blob([bin], { type: 'image/png' }))
    const W = bmp.width, H = bmp.height
    const cv = new OffscreenCanvas(W, H); const cx = cv.getContext('2d')
    cx.drawImage(bmp, 0, 0)
    const d = cx.getImageData(0, 0, W, H).data
    // Ground: median of the frame edge.
    const edge = []
    for (let x = 0; x < W; x += 4) { edge.push(x * 4, ((H - 1) * W + x) * 4) }
    for (let y = 0; y < H; y += 4) { edge.push(y * W * 4, (y * W + W - 1) * 4) }
    const med = (k) => { const v = edge.map(i => d[i + k]).sort((p, q) => p - q); return v[v.length >> 1] }
    const g = [med(0), med(1), med(2)]
    const isGround = (i) => {
      const dr = d[i] - g[0], dg = d[i + 1] - g[1], db = d[i + 2] - g[2]
      return dr * dr + dg * dg + db * db < 70 * 70 || (d[i + 1] < 90 && d[i] > 170 && d[i + 2] > 170)
    }
    const rowInk = new Int32Array(H)
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (!isGround((y * W + x) * 4)) rowInk[y]++
    const empty = (y) => rowInk[y] <= 3
    // Widest empty band in the middle 20–80 %.
    let best = null
    for (let y = Math.floor(H * 0.2); y < H * 0.8; y++) {
      if (!empty(y)) continue
      let e = y; while (e < H * 0.8 && empty(e)) e++
      if (!best || e - y > best.h) best = { y, h: e - y }
      y = e
    }
    if (!best || best.h < H * 0.015) return { ok: false, why: `no clean magenta band between the parts (best ${best ? best.h : 0}px of ${H})`, W, H }
    const box = (y0, y1) => {
      let x0 = W, x1 = -1, t = -1, b = -1
      for (let y = y0; y < y1; y++) {
        if (empty(y)) continue
        for (let x = 0; x < W; x++) if (!isGround((y * W + x) * 4)) { if (x < x0) x0 = x; if (x > x1) x1 = x }
        if (t < 0) t = y; b = y
      }
      return x1 < 0 ? null : { x: x0, y: t, w: x1 - x0 + 1, h: b - t + 1 }
    }
    const lid = box(0, best.y), body = box(best.y + best.h, H)
    if (!lid || !body) return { ok: false, why: 'a part is missing', W, H }
    if (lid.h < H * 0.1 || body.h < H * 0.15) return { ok: false, why: `parts too small (lid ${lid.h}, body ${body.h})`, W, H }
    if (body.w < lid.w * 0.6 || body.w > lid.w * 1.3) return { ok: false, why: `lid/body widths don't match (lid ${lid.w}, body ${body.w})`, W, H }
    const crop = async (r) => {
      const m = 6, c = new OffscreenCanvas(r.w + 2 * m, r.h + 2 * m), k = c.getContext('2d')
      k.fillStyle = `rgb(${g[0]},${g[1]},${g[2]})`; k.fillRect(0, 0, c.width, c.height)
      k.drawImage(cv, r.x, r.y, r.w, r.h, m, m, r.w, r.h)
      const blob = await c.convertToBlob({ type: 'image/png' })
      const u = new Uint8Array(await blob.arrayBuffer()); let s = ''
      for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode(...u.subarray(i, i + 0x8000))
      return btoa(s)
    }
    return { ok: true, W, H, gap: best, lid, body, lidPng: await crop(lid), bodyPng: await crop(body) }
  }, readFileSync(SRC).toString('base64'))
} finally { await close() }

if (!cut.ok) { console.error(`SPLIT_FAILED: ${cut.why}`); console.log(`SPLIT_FAILED: ${cut.why}`); process.exit(3) }
console.error(`painting ${cut.W}x${cut.H}, gap ${cut.gap.h}px at y=${cut.gap.y}; lid ${cut.lid.w}x${cut.lid.h}, body ${cut.body.w}x${cut.body.h}`)

rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT, { recursive: true })
const tmp = join(tmpdir(), `gift-pack-${process.pid}`); mkdirSync(tmp, { recursive: true })
const parts = {}
for (const [name, r, png] of [['lid', cut.lid, cut.lidPng], ['box', cut.body, cut.bodyPng]]) {
  const s = Math.min(1, MAX_W[name] / r.w) // never upscaled
  const w = Math.round(r.w * s), h = Math.round(r.h * s)
  const inFile = join(tmp, `${name}.png`); writeFileSync(inFile, Buffer.from(png, 'base64'))
  const base = `${name}_${w}x${h}`
  const p = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'),
    '--in', inFile, '--out-dir', OUT, '--size', `${w}x${h}`, '--fit', 'trim', '--pad', '0', '--quality', Q, '--names', base],
  { cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
  if (p.status !== 0) { console.log(`${name}: slice failed (exit ${p.status})`); process.exit(1) }
  parts[name] = { file: `${base}.webp`, w, h }
}
rmSync(tmp, { recursive: true, force: true })
const v = createHash('sha1').update(readFileSync(join(OUT, parts.lid.file))).update(readFileSync(join(OUT, parts.box.file))).digest('hex').slice(0, 8)
const f = (p) => `{ file: '${p.file}', w: ${p.w}, h: ${p.h} }`
writeReg(`{\n  lid: ${f(parts.lid)},\n  box: ${f(parts.box)},\n  v: '${v}'\n}`)
console.log(`${REG} (lid ${parts.lid.w}x${parts.lid.h}, box ${parts.box.w}x${parts.box.h}, ${v})`)
