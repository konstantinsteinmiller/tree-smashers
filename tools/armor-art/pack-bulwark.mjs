#!/usr/bin/env node
/**
 * Painted tank bulwark tile → public/images/vfx/bulwark_<W>x<H>.webp +
 * src/use/paintedBulwark.ts.
 *
 *   node tools/armor-art/pack-bulwark.mjs [--q 0.86]
 *
 * In:  art-sheets/painted/armor-bulwark.png (ONE tile).
 * The tile is trimmed and downsized to ≤ 140 px tall (drawn as tall as the
 * armour band + outline, never upscaled). A tile that is empty, touches the
 * cell edge or is not at least 1.6× as wide as tall (it would not tile along an
 * arc) REFUSES the sheet: registry null → the vector bulwark stays.
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { openCanvas } from '../art-desk/imaging.mjs'
import { PAINTED, ROOT, keyCells, trimCells } from '../sprite-pack/lib.mjs'

const a = process.argv.slice(2)
const Q = Number((() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.86' })())
const OUT = join(ROOT, 'public', 'images', 'vfx')
const REG = join(ROOT, 'src', 'use', 'paintedBulwark.ts')
const MAX_H = 140

const writeReg = (meta) => writeFileSync(REG, `// GENERATED by tools/armor-art/pack-bulwark.mjs — do not edit by hand.
// Painted tank bulwark tile in public/images/vfx/: rect [x, y, w, h] in the
// image. null = not painted / refused → the vector bulwark stays (armorArt.ts).
export interface PaintedBulwark { file: string, v: string, tile: readonly [number, number, number, number] }
export const PAINTED_BULWARK: PaintedBulwark | null = ${meta ? JSON.stringify(meta).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'").replace(/,(?=\w+:)/g, ', ') : 'null'}
`)

for (const f of existsSync(OUT) ? readdirSync(OUT) : []) if (f.startsWith('bulwark_')) rmSync(join(OUT, f))
const SRC = join(PAINTED, 'armor-bulwark.png')
if (!existsSync(SRC)) { console.error('not painted yet — vector bulwark stays'); writeReg(null); console.log(REG); process.exit(0) }
const k = keyCells(SRC, 1, 1, ['tile'])
const { page, close } = await openCanvas(ROOT)
let res
try {
  res = (await trimCells(page, [{ name: 'tile', png: k.cells.tile, maxW: MAX_H * 6, maxH: MAX_H, pad: 1 }], Q)).tile
} finally {
  await close()
  rmSync(k.tmp, { recursive: true, force: true })
}
if (!res.ok || res.w / res.h < 1.6) {
  console.error(`REFUSED — ${res.why ?? `aspect ${(res.w / res.h).toFixed(2)} < 1.6`}`)
  writeReg(null)
  process.exit(3)
}
mkdirSync(OUT, { recursive: true })
const file = `bulwark_${res.w}x${res.h}.webp`
const buf = Buffer.from(res.b64, 'base64')
writeFileSync(join(OUT, file), buf)
writeReg({ file, v: createHash('sha1').update(buf).digest('hex').slice(0, 8), tile: [0, 0, res.w, res.h] })
console.error(`${file} ${Math.round(buf.length / 1024)} kB`)
console.log(REG)
