#!/usr/bin/env node
/**
 * Painted armour tiles → one strip + src/use/paintedArmor.ts.
 *
 *   node tools/armor-art/pack.mjs [--q 0.86]
 *
 * In:  art-sheets/painted/armor-tiles.png (2 rows: plate | patch).
 * Out: public/images/vfx/armor-tiles_<W>x<H>.webp — the two keyed, trimmed
 *      tiles stacked (plate on top), each ≤ 120 px tall: a tile is drawn as
 *      tall as the armour band + its outline, ≤ 0.48 × the blade radius; the
 *      biggest boss blade (~56 units) on a 3× phone bake (~2.6 device px /
 *      unit) is ~70 px — above the sprite's own height the vector arc is drawn.
 *      Never upscaled. A tile that is not at least 1.6× as wide as tall (it
 *      would not tile along an arc), empty, or touching its half's edge
 *      REFUSES the sheet (registry null → the vector arcs stay).
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { openCanvas } from '../art-desk/imaging.mjs'
import { PAINTED, ROOT, keyCells, trimCells } from '../sprite-pack/lib.mjs'

const a = process.argv.slice(2)
const Q = Number((() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.86' })())
const OUT = join(ROOT, 'public', 'images', 'vfx')
const REG = join(ROOT, 'src', 'use', 'paintedArmor.ts')
const MAX_H = 120

const writeReg = (meta) => writeFileSync(REG, `// GENERATED by tools/armor-art/pack.mjs — do not edit by hand.
// Painted directional-armour tiles in public/images/vfx/: plate (reinforced
// zone) and patch (weak zone), rect [x, y, w, h] in the strip. null = not
// painted / refused → the vector arcs stay (armorArt.ts).
export interface PaintedArmor { file: string, v: string, plate: readonly [number, number, number, number], patch: readonly [number, number, number, number] }
export const PAINTED_ARMOR: PaintedArmor | null = ${meta ? JSON.stringify(meta).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'").replace(/,(?=\w+:)/g, ', ') : 'null'}
`)

for (const f of existsSync(OUT) ? readdirSync(OUT) : []) if (f.startsWith('armor-tiles_')) rmSync(join(OUT, f))
const SRC = join(PAINTED, 'armor-tiles.png')
if (!existsSync(SRC)) { console.error('not painted yet — vector arcs stay'); writeReg(null); console.log(REG); process.exit(0) }
const k = keyCells(SRC, 1, 2, ['plate', 'patch'])
const { page, close } = await openCanvas(ROOT)
let out
try {
  const res = await trimCells(page, ['plate', 'patch'].map(n => ({ name: n, png: k.cells[n], maxW: MAX_H * 6, maxH: MAX_H, pad: 1 })), Q)
  const bad = ['plate', 'patch'].filter(n => !res[n].ok || res[n].w / res[n].h < 1.6).map(n => `${n}: ${res[n].why ?? `aspect ${(res[n].w / res[n].h).toFixed(2)}`}`)
  if (bad.length) { console.error(`REFUSED — ${bad.join('; ')}`); writeReg(null); process.exit(3) }
  out = await page.evaluate(async ({ tiles, Q }) => {
    const W = Math.max(...tiles.map(t => t.w)); const H = tiles.reduce((s, t) => s + t.h + 2, 0)
    const c = new OffscreenCanvas(W, H); const g = c.getContext('2d')
    const rects = {}; let y = 0
    for (const t of tiles) {
      const bin = Uint8Array.from(atob(t.png), ch => ch.charCodeAt(0))
      g.drawImage(await createImageBitmap(new Blob([bin], { type: 'image/png' })), 0, y)
      rects[t.name] = [0, y, t.w, t.h]
      y += t.h + 2
    }
    const u = new Uint8Array(await (await c.convertToBlob({ type: 'image/webp', quality: Q })).arrayBuffer())
    let bs = ''
    for (let i = 0; i < u.length; i += 0x8000) bs += String.fromCharCode(...u.subarray(i, i + 0x8000))
    return { b64: btoa(bs), rects, W, H }
  }, { tiles: ['plate', 'patch'].map(n => ({ name: n, png: res[n].png, w: res[n].w, h: res[n].h })), Q })
} finally {
  await close()
  rmSync(k.tmp, { recursive: true, force: true })
}
mkdirSync(OUT, { recursive: true })
const file = `armor-tiles_${out.W}x${out.H}.webp`
const buf = Buffer.from(out.b64, 'base64')
writeFileSync(join(OUT, file), buf)
writeReg({ file, v: createHash('sha1').update(buf).digest('hex').slice(0, 8), plate: out.rects.plate, patch: out.rects.patch })
console.error(`${file} ${Math.round(buf.length / 1024)} kB`)
console.log(REG)
