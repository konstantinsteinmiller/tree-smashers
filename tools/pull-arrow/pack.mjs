#!/usr/bin/env node
/**
 * Painted pull-arrow → public/images/ui/pull-arrow_<W>x<H>.webp + src/use/paintedPullArrow.ts.
 *
 *   node tools/pull-arrow/pack.mjs [--q 0.88]
 *
 * In:  art-sheets/painted/pull-arrow.png (ONE sprite, pointing RIGHT).
 * The sprite is keyed (magenta → transparent), trimmed and downsized to ≤ 96 px
 * tall (drawn ~16 px tall × 3 DPR, never upscaled). An empty sprite, one touching
 * the cell edge, or one far from a roughly square-to-wide arrow REFUSES the sheet:
 * the registry stays null and the vector arrow (pullArrowArt.ts) stays.
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { openCanvas } from '../art-desk/imaging.mjs'
import { PAINTED, ROOT, keyCells, trimCells } from '../sprite-pack/lib.mjs'

const a = process.argv.slice(2)
const Q = Number((() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.88' })())
const OUT = join(ROOT, 'public', 'images', 'ui')
const REG = join(ROOT, 'src', 'use', 'paintedPullArrow.ts')
const MAX_H = 96

const writeReg = (meta) => writeFileSync(REG, `// GENERATED by tools/pull-arrow/pack.mjs — do not edit by hand.
// Painted "pull this smasher" arrow in public/images/ui/: one sprite pointing RIGHT (+x).
// null = not painted / refused → the vector arrow stays (pullArrowArt.ts).
export interface PaintedPullArrow { file: string, v: string, w: number, h: number }
export const PAINTED_PULL_ARROW: PaintedPullArrow | null = ${meta ? JSON.stringify(meta).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'").replace(/,(?=\w+:)/g, ', ') : 'null'}
`)

for (const f of existsSync(OUT) ? readdirSync(OUT) : []) if (f.startsWith('pull-arrow_')) rmSync(join(OUT, f))
const SRC = join(PAINTED, 'pull-arrow.png')
if (!existsSync(SRC)) { console.error('not painted yet — vector arrow stays'); writeReg(null); console.log(REG); process.exit(0) }
const k = keyCells(SRC, 1, 1, ['arrow'])
const { page, close } = await openCanvas(ROOT)
let res
try {
  res = (await trimCells(page, [{ name: 'arrow', png: k.cells.arrow, maxW: MAX_H * 2, maxH: MAX_H, pad: 1 }], Q)).arrow
} finally {
  await close()
  rmSync(k.tmp, { recursive: true, force: true })
}
const aspect = res.ok ? res.w / res.h : 0
if (!res.ok || aspect < 0.7 || aspect > 2.2) {
  console.error(`REFUSED — ${res.why ?? `aspect ${aspect.toFixed(2)} outside 0.7 … 2.2`}`)
  writeReg(null)
  process.exit(3)
}
mkdirSync(OUT, { recursive: true })
const file = `pull-arrow_${res.w}x${res.h}.webp`
const buf = Buffer.from(res.b64, 'base64')
writeFileSync(join(OUT, file), buf)
writeReg({ file, v: createHash('sha1').update(buf).digest('hex').slice(0, 8), w: res.w, h: res.h })
console.error(`${file} ${Math.round(buf.length / 1024)} kB`)
console.log(REG)
