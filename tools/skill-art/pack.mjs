#!/usr/bin/env node
/**
 * Painted skill icons + flavour sprites → WebP + the generated registry.
 *
 *   node tools/skill-art/pack.mjs [--q 0.84]
 *
 * In:  art-sheets/painted/skill-<sheet>.png   (3×3 / 3×2 sheets on magenta, paint-queue.mjs)
 *      art-sheets/painted/skill-icon-<id>.png (solo repaints of rejected cells)
 *      art-sheets/skill-art/rejected.json     (reviewer verdicts — rejected cells are skipped)
 * Out: public/images/skills/<skillId>.webp    128 px — the largest use is the
 *        36 css px Team-modal medallion (art box 0.78 × 36 ≈ 28 px) × 3 DPR = 84,
 *        plus head-room for the dev sheet; a sheet cell is ~340 px, never upscaled.
 *      public/images/skills/fx/<shape>.webp    64 px — a flavour particle is ≤ 11
 *        arena px (size 5.5 × 2) × camera zoom × 3 DPR.
 *      src/use/skills/paintedSkillArt.ts — the generated registry (id → content
 *        hash) smasherSkillArt.ts reads; an id missing from it keeps the drawing.
 * Keying, trim, 4 % margin and the grid gap-snap: tools/art-desk/slice.mjs.
 * Webps of ids no longer painted (rejected later) are deleted, so a file
 * never outlives its registry entry.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { FLAVOUR_IDS, SHEETS, SKILLS, readRejected } from './prompts.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const Q = (() => { const i = a.indexOf('--q'); return i >= 0 ? a[i + 1] : '0.84' })()
const PAINTED = join(ROOT, 'art-sheets', 'painted')
const OUT = join(ROOT, 'public', 'images', 'skills')
const OUT_FX = join(OUT, 'fx')
const TMP = join(ROOT, 'art-sheets', 'skill-art', '.pack-tmp')
const REG = join(ROOT, 'src', 'use', 'skills', 'paintedSkillArt.ts')
export const ICON_PX = 128
export const FX_PX = 64
mkdirSync(OUT_FX, { recursive: true })

const rej = readRejected()
const slice = (src, grid, px, names) => {
  rmSync(TMP, { recursive: true, force: true }); mkdirSync(TMP, { recursive: true })
  const r = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'),
    '--in', src, '--out-dir', TMP, '--grid', grid, '--size', `${px}x${px}`, '--fit', 'trim', '--pad', '0.04', '--quality', Q, '--names', names.join(',')],
  { cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
  return r.status === 0
}
const icons = {}
const fx = {}
const take = (id, dir, into) => {
  const f = join(TMP, `${id}.webp`)
  if (!existsSync(f)) return
  renameSync(f, join(dir, `${id}.webp`))
  into[id] = createHash('sha1').update(readFileSync(join(dir, `${id}.webp`))).digest('hex').slice(0, 8)
}

// Solo repaints win over their sheet cell (the cell was rejected anyway).
const solo = (id) => existsSync(join(PAINTED, `skill-icon-${id}.png`)) && !rej[id]?.single
for (const s of SHEETS) {
  const src = join(PAINTED, `skill-${s.name}.png`)
  if (!existsSync(src)) { console.error(`${s.name}: not painted yet — drawings stay`); continue }
  const names = s.ids.map(id => (!id || rej[id]?.sheet || (s.kind === 'icon' && solo(id))) ? '-' : id)
  if (!slice(src, `${s.cols}x${s.rows}`, s.kind === 'icon' ? ICON_PX : FX_PX, names)) { console.error(`${s.name}: slice failed — drawings stay`); continue }
  for (const id of names) if (id !== '-') take(id, s.kind === 'icon' ? OUT : OUT_FX, s.kind === 'icon' ? icons : fx)
  console.error(`${s.name}: ${names.filter(n => n !== '-').length} cells`)
}
for (const [id] of SKILLS) {
  if (!solo(id)) continue
  if (slice(join(PAINTED, `skill-icon-${id}.png`), '1x1', ICON_PX, [id])) take(id, OUT, icons)
  console.error(`single ${id}: ${icons[id] ? 'ok' : 'failed'}`)
}
rmSync(TMP, { recursive: true, force: true })

// No orphan files: a webp without a registry entry is removed.
for (const f of readdirSync(OUT)) if (f.endsWith('.webp') && !icons[f.slice(0, -5)]) rmSync(join(OUT, f))
for (const f of readdirSync(OUT_FX)) if (f.endsWith('.webp') && !fx[f.slice(0, -5)]) rmSync(join(OUT_FX, f))

const order = (ids, m) => ids.filter(id => m[id]).map(id => `  ${id}: '${m[id]}'`)
const iconRows = order(SKILLS.map(s => s[0]), icons)
const fxRows = order(FLAVOUR_IDS, fx)
writeFileSync(REG, `// GENERATED by tools/skill-art/pack.mjs — do not edit by hand.
// Painted smasher skill icons (public/images/skills/<id>.webp, ${ICON_PX} px) and
// skill VFX flavour sprites (public/images/skills/fx/<shape>.webp, ${FX_PX} px):
// id → content hash (the cache key). A missing id keeps its procedural
// drawing (src/use/skills/smasherSkillArt.ts), as does \`?art=procedural\`.
export const PAINTED_SKILL_ICONS: Readonly<Record<string, string>> = {${iconRows.length ? `\n${iconRows.join(',\n')}\n` : ''}}
export const PAINTED_SKILL_FX: Readonly<Record<string, string>> = {${fxRows.length ? `\n${fxRows.join(',\n')}\n` : ''}}
`)
console.log(`${REG} (${iconRows.length}/${SKILLS.length} icons, ${fxRows.length}/${FLAVOUR_IDS.length} fx painted)`)
