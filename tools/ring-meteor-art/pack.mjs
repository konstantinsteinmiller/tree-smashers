#!/usr/bin/env node
/**
 * Painted ring meteors → one small webp per palette family + the registry.
 *
 *   node tools/ring-meteor-art/pack.mjs [--ppu 3.2] [--q 0.85]
 *
 * In:  art-sheets/painted/ring-meteor-<fire|ice|candy>.png (paint-queue.mjs).
 * Out: public/images/vfx/ring-meteor-<family>_<w>x<h>.webp — keyed to alpha by
 *      the Art Desk slicer (tools/art-desk/slice.mjs), trimmed; and
 *      src/use/paintedRingMeteors.ts (rect = opaque bbox, anchor = head centre:
 *      half the sprite height in from its right edge, mid height).
 * Never touches the kept strike variant's files (meteor_*.webp, paintedMeteors.ts).
 *
 * Resolution (never upscaled): the sprite width = PPU × the longest on-screen
 * ring meteor in arena units (head r ≤ 8.4, trail ≤ 9.2 r + 1.3 r ≈ 88 units)
 * → 282 px at PPU 3.2; a 3× phone draws ~2.2 device px per unit. The renderer
 * still falls back to the procedural meteor above 1.02 device px per sprite px.
 * Families not painted yet are left out (their themes draw procedurally);
 * no painting at all → registry `null`. Exit: 0 ok · 2 nothing painted · 1 failed.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openCanvas } from '../art-desk/imaging.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const opt = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d }
const PPU = +opt('ppu', 3.2)
const Q = opt('q', '0.85')
const MAX_LEN = 88
const FAMILIES = ['fire', 'ice', 'candy']
const OUT = join(ROOT, 'public', 'images', 'vfx')
const REG = join(ROOT, 'src', 'use', 'paintedRingMeteors.ts')

const header = `// GENERATED by tools/ring-meteor-art/pack.mjs — do not edit by hand.
// Painted meteors for the ring meteor shower (src/use/ringShower.ts): one
// sprite per palette family (fire / ice / candy), each its own webp in
// public/images/vfx/. Rect = opaque bbox (px), anchor = the head centre.
// The meteor travels along +x (head right, trail left).
// null until the Art Desk paintings exist — the procedural shapes draw then.
export type RingMeteorFamily = 'fire' | 'ice' | 'candy'
export interface PaintedRingMeteorSprite { file: string, v: string, x: number, y: number, w: number, h: number, ax: number, ay: number }
export interface PaintedRingMeteorAtlas {
  sprites: Partial<Record<RingMeteorFamily, PaintedRingMeteorSprite>>
}
`
const writeReg = (body) => writeFileSync(REG, `${header}export const PAINTED_RING_METEOR_ART: PaintedRingMeteorAtlas | null = ${body}\n`)

const painted = FAMILIES.filter(f => existsSync(join(ROOT, 'art-sheets', 'painted', `ring-meteor-${f}.png`)))
if (painted.length === 0) {
  console.error('ring-meteor: nothing painted yet — procedural meteors stay')
  writeReg('null')
  process.exit(2)
}
mkdirSync(OUT, { recursive: true })
const W = Math.round(MAX_LEN * PPU)
const H = Math.round(W / 3)
const { page, close } = await openCanvas(ROOT)
const entries = []
try {
  for (const fam of painted) {
    const src = join(ROOT, 'art-sheets', 'painted', `ring-meteor-${fam}.png`)
    const base = `ring-meteor-${fam}_${W}x${H}`
    const r = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'),
      '--in', src, '--out-dir', OUT, '--size', `${W}x${H}`, '--fit', 'trim', '--pad', '0.01', '--quality', Q, '--names', base],
    { cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
    if (r.status !== 0) { console.error(`ring-meteor ${fam}: slice failed (exit ${r.status})`); continue }
    const file = `${base}.webp`
    const bytes = readFileSync(join(OUT, file))
    const box = await page.evaluate(async (b64) => {
      const bin = Uint8Array.from(atob(b64), c => c.charCodeAt(0))
      const bmp = await createImageBitmap(new Blob([bin], { type: 'image/webp' }))
      const cv = new OffscreenCanvas(bmp.width, bmp.height)
      const cx = cv.getContext('2d')
      cx.drawImage(bmp, 0, 0)
      const d = cx.getImageData(0, 0, bmp.width, bmp.height).data
      let x0 = bmp.width; let y0 = bmp.height; let x1 = -1; let y1 = -1
      for (let y = 0; y < bmp.height; y++) {
        for (let x = 0; x < bmp.width; x++) {
          if (d[(y * bmp.width + x) * 4 + 3] > 24) {
            if (x < x0) x0 = x
            if (x > x1) x1 = x
            if (y < y0) y0 = y
            if (y > y1) y1 = y
          }
        }
      }
      return x1 < 0 ? null : { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1 }
    }, bytes.toString('base64'))
    if (!box || box.w < box.h * 2) {
      console.error(`ring-meteor ${fam}: REFUSED — sprite ${box ? `${box.w}×${box.h}` : 'empty'} is not a horizontal meteor (re-paint)`)
      continue
    }
    const v = createHash('sha1').update(bytes).digest('hex').slice(0, 8)
    entries.push(`    ${fam}: { file: '${file}', v: '${v}', x: ${box.x}, y: ${box.y}, w: ${box.w}, h: ${box.h}, ax: ${Math.round(box.w - box.h / 2)}, ay: ${Math.round(box.h / 2)} }`)
    console.error(`ring-meteor ${fam}: ${box.w}×${box.h} in ${file} (${bytes.length} B)`)
  }
} finally {
  await close()
}
if (entries.length === 0) { writeReg('null'); process.exit(1) }
writeReg(`{\n  sprites: {\n${entries.join(',\n')}\n  }\n}`)
console.log(`${REG} (${entries.length} ring meteor sprite(s))`)
