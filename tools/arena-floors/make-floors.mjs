#!/usr/bin/env node
/**
 * Painted arena floors → runtime WebPs + registry.
 *
 *   node tools/arena-floors/make-floors.mjs [--size 1024] [--q 0.8]
 *
 * In:  art-sheets/painted/arena-floor-<theme>-<n>.png — a full-bleed, square,
 *      top-down ground painting: floor variant <n> of an arena theme
 *      (arenaThemes.ts FLOOR_PLAN / floorKeyFor picks a variant per layout;
 *      prompts in art-sheets/arena-floors/<theme>-<n>.prompt.txt, written by
 *      tools/arena-themes/prompts.mjs — TEXT-ONLY, no reference; the
 *      clearing's SHAPE is not painted: the engine clips the painting to
 *      the layout's SDF outline, and the feature sprites + rim draw on top).
 * Out: public/images/arena-floors/<theme>-<n>_<s>x<s>.webp;
 *      src/use/paintedFloors.ts — generated registry { '<theme>-<n>': { file, size, v } }.
 *
 * The painting covers the clearing's bounding square (2 × ARENA_RADIUS =
 * 400 units): at 1024 px that is 2.56 px per arena unit — phone 3× (≈2.5)
 * and desktop 1080p (≈2.3) draw it at or below its own resolution; the
 * engine falls back to the procedural floor above 1.5× upscaling.
 */
import { createRequire } from 'node:module'
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const require = createRequire(join(ROOT, 'package.json'))
const { chromium } = require('playwright')
const a = process.argv.slice(2)
const opt = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d }
const SIZE = +opt('size', 1024)
const Q = +opt('q', 0.8)
const paintedDir = join(ROOT, 'art-sheets', 'painted')
const OUT_DIR = join(ROOT, 'public', 'images', 'arena-floors')
const ids = readdirSync(paintedDir)
  .map(f => /^arena-floor-([a-z]+-\d+)\.png$/.exec(f)?.[1])
  .filter(Boolean)
  .sort()
if (ids.length === 0) { console.error('no art-sheets/painted/arena-floor-<theme>-<n>.png'); process.exit(2) }
mkdirSync(OUT_DIR, { recursive: true })

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const reg = {}
try {
  const page = await browser.newPage()
  for (const id of ids) {
    const src = join(paintedDir, `arena-floor-${id}.png`)
    const b64 = await page.evaluate(async ([url, SIZE, Q]) => {
      const img = new Image()
      img.src = url
      await img.decode()
      const s = Math.min(SIZE, img.width, img.height)
      const c = new OffscreenCanvas(s, s)
      const x = c.getContext('2d')
      x.imageSmoothingQuality = 'high'
      x.drawImage(img, 0, 0, s, s)
      const blob = await c.convertToBlob({ type: 'image/webp', quality: Q })
      const buf = new Uint8Array(await blob.arrayBuffer())
      let bin = ''
      for (let i = 0; i < buf.length; i += 0x8000) bin += String.fromCharCode(...buf.subarray(i, i + 0x8000))
      return [btoa(bin), s]
    }, [`data:image/png;base64,${readFileSync(src).toString('base64')}`, SIZE, Q])
    const buf = Buffer.from(b64[0], 'base64')
    const s = b64[1]
    const file = `${id}_${s}x${s}.webp`
    writeFileSync(join(OUT_DIR, file), buf)
    reg[id] = { file, size: s, v: createHash('sha1').update(buf).digest('hex').slice(0, 8) }
    console.log(`${file} ${(buf.length / 1024).toFixed(1)} kB`)
  }
} finally {
  await browser.close()
}
const keep = new Set(Object.values(reg).map(r => r.file))
for (const f of readdirSync(OUT_DIR)) if (f.endsWith('.webp') && !keep.has(f)) unlinkSync(join(OUT_DIR, f))
const rows = Object.entries(reg).map(([id, r]) => `  '${id}': { file: ${JSON.stringify(r.file)}, size: ${r.size}, v: '${r.v}' }`)
writeFileSync(join(ROOT, 'src', 'use', 'paintedFloors.ts'), `// GENERATED by tools/arena-floors/make-floors.mjs — do not edit by hand.
// Painted clearing floors in public/images/arena-floors/, keyed by floor
// variant '<theme>-<n>' (arenaThemes.ts floorKeyFor): a square top-down ground
// covering the clearing's bounding box (2 × ARENA_RADIUS), clipped to the
// layout's outline at draw time.
export const PAINTED_FLOORS: Readonly<Record<string, { file: string, size: number, v: string }>> = {
${rows.join(',\n')}
}
`)
if (!existsSync(join(ROOT, 'src', 'use', 'paintedFloors.ts'))) process.exit(1)
