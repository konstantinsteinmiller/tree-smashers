#!/usr/bin/env node
/**
 * Painted meteor → ONE small runtime atlas + the generated registry.
 *
 *   node tools/meteor-art/pack.mjs [--ppu 3.2] [--q 0.85]
 *
 * In:  art-sheets/painted/meteor-meteor.png (paint-queue.mjs; one meteor on flat
 *      magenta, head on the right, trail to the left).
 * Out: public/images/vfx/meteor_<w>x<h>.webp — keyed to alpha (the Art Desk
 *      slicer, tools/art-desk/slice.mjs: ground measured on the frame, magenta
 *      fringe unmixed), trimmed, centred; src/use/paintedMeteors.ts — the
 *      registry meteorShower.ts reads (sprite rect = the opaque bbox, anchor =
 *      the head centre: half the sprite height in from its right edge, mid
 *      height — the flame front is a half-disc round the head).
 *
 * Resolution (render-sharpness rule — never upscaled): the sprite's width maps
 * to PPU × the largest on-screen meteor length in arena units (the hero: head
 * r 20, trail 8 r → 160 + 1.3 r = 186 units). At PPU 3.2 that is 595 px — a 3×
 * phone draws ~2.2 device px per unit, a 1080p desktop ~2.3, so every use
 * downsamples; the renderer still falls back to the procedural meteor when a
 * sprite would be stretched past 1.02 device px per atlas px.
 * With no painting the registry is written as `null` (procedural only).
 * Exit: 0 ok · 2 no painting · 1 failed.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openCanvas } from '../art-desk/imaging.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const a = process.argv.slice(2)
const opt = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d }
const PPU = +opt('ppu', 3.2)
const Q = opt('q', '0.85')
const HERO_LEN = 20 * 8 + 1.3 * 20
const OUT = join(ROOT, 'public', 'images', 'vfx')
const REG = join(ROOT, 'src', 'use', 'paintedMeteors.ts')
const SRC = join(ROOT, 'art-sheets', 'painted', 'meteor-meteor.png')

const header = `// GENERATED by tools/meteor-art/pack.mjs — do not edit by hand.
// Painted meteor-shower art in public/images/vfx/ (src/use/meteorShower.ts):
// one atlas; the sprite's rect (atlas px) and its anchor (the meteor's head
// centre, atlas px from the rect's top-left). The meteor travels along +x
// (head on the right, flame trail to the left).
// null until the Art Desk paintings exist — the procedural shapes draw then.
export interface PaintedMeteorSprite { x: number, y: number, w: number, h: number, ax: number, ay: number }
export interface PaintedMeteorAtlas {
  file: string
  v: string
  meteor: PaintedMeteorSprite
}
`
const writeReg = (body) => writeFileSync(REG, `${header}export const PAINTED_METEOR_ART: PaintedMeteorAtlas | null = ${body}\n`)

if (!existsSync(SRC)) {
  console.error('meteor: not painted yet (art-sheets/painted/meteor-meteor.png) — procedural meteor stays')
  writeReg('null')
  process.exit(2)
}
mkdirSync(OUT, { recursive: true })
const W = Math.round(HERO_LEN * PPU)
const H = Math.round(W / 3)
const base = `meteor_${W}x${H}`
const r = spawnSync(process.execPath, [join(ROOT, 'tools', 'art-desk', 'slice.mjs'),
  '--in', SRC, '--out-dir', OUT, '--size', `${W}x${H}`, '--fit', 'trim', '--pad', '0.01', '--quality', Q, '--names', base],
{ cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] })
if (r.status !== 0) { console.error(`meteor: slice failed (exit ${r.status})`); process.exit(1) }
const file = `${base}.webp`
const bytes = readFileSync(join(OUT, file))

// Opaque bbox of the sliced sprite (headless Chrome — the project ships no sharp).
const { page, close } = await openCanvas(ROOT)
let box
try {
  box = await page.evaluate(async (b64) => {
    const bin = Uint8Array.from(atob(b64), c => c.charCodeAt(0))
    const bmp = await createImageBitmap(new Blob([bin], { type: 'image/webp' }))
    const cv = new OffscreenCanvas(bmp.width, bmp.height)
    const cx = cv.getContext('2d')
    cx.drawImage(bmp, 0, 0)
    const d = cx.getImageData(0, 0, bmp.width, bmp.height).data
    let x0 = bmp.width; let y0 = bmp.height; let x1 = -1; let y1 = -1
    for (let y = 0; y < bmp.height; y++) {
      for (let x = 0; x < bmp.width; x++) {
        if (d[(y * bmp.width + x) * 4 + 3] > 24) {
          if (x < x0) x0 = x
          if (x > x1) x1 = x
          if (y < y0) y0 = y
          if (y > y1) y1 = y
        }
      }
    }
    return x1 < 0 ? null : { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1 }
  }, bytes.toString('base64'))
} finally {
  await close()
}
if (!box || box.w < box.h * 2) {
  console.error(`meteor: REFUSED — sprite ${box ? `${box.w}×${box.h}` : 'empty'} is not a horizontal meteor (re-paint)`)
  writeReg('null')
  process.exit(1)
}
const v = createHash('sha1').update(bytes).digest('hex').slice(0, 8)
const ax = Math.round(box.w - box.h / 2)
const ay = Math.round(box.h / 2)
writeReg(`{
  file: '${file}',
  v: '${v}',
  meteor: { x: ${box.x}, y: ${box.y}, w: ${box.w}, h: ${box.h}, ax: ${ax}, ay: ${ay} }
}`)
console.log(`${REG} (meteor ${box.w}×${box.h} in ${file}, ${bytes.length} B)`)
