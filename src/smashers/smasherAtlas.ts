// ─── Smasher atlas ──────────────────────────────────────────────────────────
//
// Prerendered smasher art for the battle canvas and the DOM:
//  - character SHEETS: the 32 yaw frames of one (smasher, skin, boss) look at
//    one resolution bucket, in a 4 × 4 grid on one offscreen canvas. Frames
//    are drawn lazily (first use) and the sheets live in a pixel-bounded LRU.
//  - DISC sprites: the top face of the turning disc (wood + team-coloured
//    rim + spin marks), drawn as a top-view circle; the battle draw squashes
//    and rotates it.
//  - PORTRAITS: a front 3/4 view on its disc as a cached data URL for <img>s.
//
// Resolution rule (render sharpness): a sheet's pixels-per-unit is the
// smallest bucket ≥ the device pixels the blade covers (radius × the canvas
// transform scale, which already includes the DPR), capped at 2× that — never
// drawn below css × dpr.

import { prependBaseUrl } from '@/utils/function'
import type { SmasherId } from '@/data/smasherCatalog'
import {
  DISC_SQUASH, DISC_THICKNESS, FRAME_BOX, FRAME_H, FRAME_W, YAW_COLS, YAW_FRAMES, drawSmasher, frameYaw, mixHex
} from '@/smashers/smasherRig'
import { lookKey, smasherForSkin, smasherPalette } from '@/smashers/smasherSkins'
import { PAINTED_SMASHERS, type PaintedSmasherSheet } from '@/smashers/paintedSmashers'
import { PAINTED_PORTRAITS, type PaintedPortrait } from '@/smashers/paintedPortraits'

const BUCKETS = [12, 16, 20, 26, 32, 40, 50, 64, 80, 100, 128, 160, 200]
const COLS = YAW_COLS

/** Smallest bucket ≥ `need` device px per model unit. */
export const atlasBucket = (need: number): number => {
  for (const b of BUCKETS) if (b >= need) return b
  return BUCKETS[BUCKETS.length - 1]!
}

const makeCanvas = (w: number, h: number): HTMLCanvasElement | OffscreenCanvas | null => {
  try {
    if (typeof navigator !== 'undefined' && /jsdom/i.test(navigator.userAgent)) return null
    if (typeof document !== 'undefined') {
      const c = document.createElement('canvas')
      c.width = w
      c.height = h
      return c.getContext('2d') ? c : null
    }
    if (typeof OffscreenCanvas !== 'undefined') return new OffscreenCanvas(w, h)
  } catch { /* no canvas (tests) */ }
  return null
}

type Ctx2D = CanvasRenderingContext2D | OffscreenCanvasRenderingContext2D

interface Sheet {
  canvas: HTMLCanvasElement | OffscreenCanvas
  ctx: Ctx2D
  cellW: number
  cellH: number
  ppu: number
  drawn: number
  id: SmasherId
  modelId?: string
  boss: boolean
}

// LRU by insertion order (a Map re-inserted on use), bounded by total pixels.
const PIXEL_BUDGET = 20_000_000
const sheets = new Map<string, Sheet | null>()
let sheetPixels = 0

const evict = () => {
  for (const [k, s] of sheets) {
    if (sheetPixels <= PIXEL_BUDGET) break
    sheets.delete(k)
    if (s) sheetPixels -= s.canvas.width * s.canvas.height
  }
}

const getSheet = (id: SmasherId, modelId: string | undefined, boss: boolean, ppu: number): Sheet | null => {
  const key = `${lookKey(id, modelId, boss)}@${ppu}`
  const hit = sheets.get(key)
  if (hit !== undefined) {
    sheets.delete(key)
    sheets.set(key, hit)
    return hit
  }
  const cellW = Math.ceil(FRAME_W * ppu)
  const cellH = Math.ceil(FRAME_H * ppu)
  const canvas = makeCanvas(cellW * COLS, cellH * Math.ceil(YAW_FRAMES / COLS))
  const ctx = canvas ? (canvas.getContext('2d') as Ctx2D | null) : null
  const sheet = canvas && ctx ? { canvas, ctx, cellW, cellH, ppu, drawn: 0, id, modelId, boss } : null
  sheets.set(key, sheet)
  if (sheet) {
    sheetPixels += sheet.canvas.width * sheet.canvas.height
    evict()
  }
  return sheet
}

const ensureFrame = (s: Sheet, frame: number) => {
  const bit = 1 << frame
  if (s.drawn & bit) return
  s.drawn |= bit
  const cx = (frame % COLS) * s.cellW
  const cy = Math.floor(frame / COLS) * s.cellH
  drawSmasher(s.ctx as CanvasRenderingContext2D, s.id, smasherPalette(s.id, s.modelId), frameYaw(frame),
    cx - FRAME_BOX.left * s.ppu, cy - FRAME_BOX.top * s.ppu, s.ppu, { boss: s.boss })
}

export interface SmasherFrameRef {
  image: CanvasImageSource
  sx: number
  sy: number
  sw: number
  sh: number
  /** Pixels per model unit of the source. */
  ppu: number
}

// ─── Painted override ────────────────────────────────────────────────────────
//
// A smasher listed in PAINTED_SMASHERS (generated by
// tools/smasher-sheets/slice-painted.mjs) has a hand-painted 8 × 4 sheet on the
// SAME lattice as the reference the rig exports: cell c px, FRAME_BOX scaled to
// 0.94 c, centred. Character only — the disc stays the live procedural layer.
// Used for the signature look only (skins + boss dress keep the rig), and only
// while its pixels-per-unit ≥ the device px the frame needs (never drawn below
// css × dpr: a bigger draw falls back to the rig at its own bucket).
// `?art=procedural` turns the layer off for an A/B.
const PAINTED_OFF = typeof location !== 'undefined' && /[?&]art=procedural(?:&|$)/.test(location.search)

interface PaintedSheet {
  img: HTMLImageElement
  ready: boolean
  cell: number
  ppu: number
  /** Yaw frames this image holds, in cell order (null = all 32 on the 8 × 4 sheet). */
  frames: readonly number[] | null
  /** Which half of the 32 yaw frames to trust: the other half is drawn as its mirror image. */
  keep?: 'early' | 'late'
}

/**
 * Sheets whose two halves were painted in different styles (tools/smasher-sheets/
 * audit-painted.mjs: HALVES-DIFFER / FACES-WRONG): the half named here is the
 * consistent one and the other half is its mirror image, so the character does not
 * change colour or style as it turns. Drop a row when the sheet is repainted.
 */
const PAINTED_KEEP: Partial<Record<string, 'early' | 'late'>> = {
  thumper: 'late',
  flamenca: 'late',
  snapjaw: 'late'
}
const painted = new Map<SmasherId, PaintedSheet | null>()
const paintedHi = new Map<SmasherId, PaintedSheet | null>()

/** Pixels per model unit of a painted cell on the rig's lattice (FRAME_BOX at 0.94 of a cell). */
export const paintedLatticePpu = (cell: number): number => (cell * 0.94) / Math.max(FRAME_W, FRAME_H)

/**
 * The hi-res portrait of `id` (tools/smasher-sheets/portraits.mjs), only while
 * the sheet it was cut with still ships: no sheet line, or a re-cut sheet (a
 * different hash), and the portrait is ignored — it can never outlive or
 * disagree with the painted sheet the battle draws.
 */
export const paintedPortraitFor = (
  id: string,
  sheets: Readonly<Record<string, PaintedSmasherSheet>> = PAINTED_SMASHERS,
  portraits: Readonly<Record<string, PaintedPortrait>> = PAINTED_PORTRAITS
): PaintedPortrait | null => {
  const p = portraits[id]
  const s = sheets[id]
  return p && s && p.sheet === s.v ? p : null
}

// Redraw hooks: a portrait drawn before its painting decoded asks to be redrawn.
const artListeners = new Set<() => void>()
/** Call `cb` whenever a painted sheet / portrait finishes loading. Returns the unsubscribe. */
export const onPaintedArtReady = (cb: () => void): (() => void) => {
  artListeners.add(cb)
  return () => { artListeners.delete(cb) }
}

const noImages = () => typeof Image === 'undefined' || (typeof navigator !== 'undefined' && /jsdom/i.test(navigator.userAgent))

const loadPainted = (
  cache: Map<SmasherId, PaintedSheet | null>, id: SmasherId,
  meta: { file: string, cell: number, v: string } | null | undefined, dir: string, frames: readonly number[] | null
): PaintedSheet | null => {
  let p = cache.get(id)
  if (p === undefined) {
    if (!meta || noImages()) {
      cache.set(id, null)
      return null
    }
    const img = new Image()
    const sheet: PaintedSheet = { img, ready: false, cell: meta.cell, ppu: paintedLatticePpu(meta.cell), frames, keep: dir === '' ? PAINTED_KEEP[id] : undefined }
    img.decoding = 'async'
    img.onload = () => {
      sheet.ready = true
      for (const k of [...portraits.keys()]) if (k.startsWith(`${id}|`)) portraits.delete(k)
      for (const cb of [...artListeners]) cb()
    }
    img.onerror = () => cache.set(id, null)
    img.src = prependBaseUrl(`images/smashers/${dir}${meta.file}?v=${meta.v}`)
    cache.set(id, sheet)
    p = sheet
  }
  return p && p.ready ? p : null
}

const paintedLook = (id: SmasherId, modelId: string | undefined, boss: boolean) =>
  !PAINTED_OFF && !boss && lookKey(id, modelId, false) === `${id}||`

// A boss wears its smasher's painted sheet too (plus a drawn crown, see `drawBossCrown`).
const paintedSheet = (id: SmasherId, modelId: string | undefined, _boss: boolean): PaintedSheet | null =>
  paintedLook(id, modelId, false) ? loadPainted(painted, id, PAINTED_SMASHERS[id], '', null) : null

/** The hi-res portrait frames (VS screen, DOM portraits), when loaded and still matching the shipped sheet. */
const paintedPortrait = (id: SmasherId, modelId: string | undefined, boss: boolean): PaintedSheet | null => {
  if (!paintedLook(id, modelId, boss)) return null
  const meta = paintedPortraitFor(id)
  return loadPainted(paintedHi, id, meta, 'portraits/', meta ? meta.frames : null)
}

/** Start fetching the painted sheets (and hi-res portraits) of these smashers (e.g. both teams before a battle). */
export const preloadPaintedSmashers = (ids: readonly SmasherId[], withPortraits = true) => {
  for (const id of ids) {
    paintedSheet(id, undefined, false)
    if (withPortraits) paintedPortrait(id, undefined, false)
  }
}

const hasFrame = (p: PaintedSheet, frame: number) => {
  const f = ((frame % YAW_FRAMES) + YAW_FRAMES) % YAW_FRAMES
  return !p.frames || p.frames.includes(f)
}

/** Draw the painted frame with the disc centre at (x, y); `scale` css px per model unit. */
const drawPainted = (ctx: CanvasRenderingContext2D, p: PaintedSheet, frame: number, x: number, y: number, scale: number) => {
  let f = ((frame % YAW_FRAMES) + YAW_FRAMES) % YAW_FRAMES
  let flip = false
  const half = YAW_FRAMES / 2
  if (p.keep === 'late' && f < half) { f = f === 0 ? YAW_FRAMES - 1 : YAW_FRAMES - f; flip = true }
  else if (p.keep === 'early' && f > half) { f = YAW_FRAMES - f; flip = true }
  const c = p.cell
  const idx = p.frames ? Math.max(0, p.frames.indexOf(f)) : f
  const cols = p.frames ? p.frames.length : COLS
  const k = scale / p.ppu
  const mid = (FRAME_BOX.top + FRAME_BOX.bottom) / 2
  const dx = x - (c / 2) * k
  const dy = y - (c / 2 - mid * p.ppu) * k
  if (flip) {
    ctx.save()
    ctx.translate(x, 0)
    ctx.scale(-1, 1)
    ctx.drawImage(p.img, (idx % cols) * c, Math.floor(idx / cols) * c, c, c, dx - x, dy, c * k, c * k)
    ctx.restore()
    return
  }
  ctx.drawImage(p.img, (idx % cols) * c, Math.floor(idx / cols) * c, c, c, dx, dy, c * k, c * k)
}

/** Source rect of one yaw frame, rendered on demand. Null without a canvas. */
export const smasherFrame = (
  id: SmasherId, modelId: string | undefined, boss: boolean, frame: number, devicePxPerUnit: number
): SmasherFrameRef | null => {
  const s = getSheet(id, modelId, boss, atlasBucket(devicePxPerUnit))
  if (!s) return null
  const f = ((frame % YAW_FRAMES) + YAW_FRAMES) % YAW_FRAMES
  ensureFrame(s, f)
  return { image: s.canvas, sx: (f % COLS) * s.cellW, sy: Math.floor(f / COLS) * s.cellH, sw: s.cellW, sh: s.cellH, ppu: s.ppu }
}

let crownImg: HTMLImageElement | null = null
/** The painted crown sprite once decoded (starts loading on first use). */
const paintedCrown = (): HTMLImageElement | null => {
  if (!crownImg && !noImages()) {
    crownImg = new Image()
    crownImg.decoding = 'async'
    crownImg.onload = () => { for (const cb of [...artListeners]) cb() }
    crownImg.src = prependBaseUrl('images/smashers/boss-crown.webp')
  }
  return crownImg && crownImg.complete && crownImg.naturalWidth > 0 ? crownImg : null
}

/** Gold crown over a painted boss's head: the painted sprite, a drawn one until it loads. */
const drawBossCrown = (ctx: CanvasRenderingContext2D, x: number, y: number, radius: number) => {
  const w = radius * 0.95
  const h = radius * 0.5
  const cx = x
  const base = y - radius * 1.35
  const img = paintedCrown()
  if (img) {
    const dw = radius * 0.95
    const dh = dw * (img.naturalHeight / img.naturalWidth)
    ctx.drawImage(img, cx - dw / 2, base - dh + radius * 0.08, dw, dh)
    return
  }
  ctx.save()
  ctx.lineJoin = 'round'
  ctx.lineWidth = Math.max(1, radius * 0.07)
  ctx.strokeStyle = '#2a1a10'
  ctx.fillStyle = '#ffcf3f'
  ctx.beginPath()
  ctx.moveTo(cx - w / 2, base)
  ctx.lineTo(cx - w / 2, base - h * 0.7)
  ctx.lineTo(cx - w / 4, base - h * 0.35)
  ctx.lineTo(cx, base - h)
  ctx.lineTo(cx + w / 4, base - h * 0.35)
  ctx.lineTo(cx + w / 2, base - h * 0.7)
  ctx.lineTo(cx + w / 2, base)
  ctx.closePath()
  ctx.fill()
  ctx.stroke()
  ctx.fillStyle = '#d8433f'
  ctx.beginPath()
  ctx.arc(cx, base - h * 0.32, radius * 0.07, 0, Math.PI * 2)
  ctx.fill()
  ctx.restore()
}

/**
 * Draw a smasher frame with the disc centre at (x, y) and `radius` css px per
 * model unit. `devicePxPerUnit` = radius × the context's device scale.
 */
export const drawSmasherFrame = (
  ctx: CanvasRenderingContext2D, id: SmasherId, modelId: string | undefined, boss: boolean,
  frame: number, x: number, y: number, radius: number, deviceScale: number
): boolean => {
  const p = paintedSheet(id, modelId, boss)
  if (p && p.ppu >= radius * deviceScale) {
    drawPainted(ctx, p, frame, x, y, radius)
    if (boss) drawBossCrown(ctx, x, y, radius)
    return true
  }
  const ref = smasherFrame(id, modelId, boss, frame, radius * deviceScale)
  if (!ref) return false
  ctx.drawImage(ref.image, ref.sx, ref.sy, ref.sw, ref.sh,
    x + FRAME_BOX.left * radius, y + FRAME_BOX.top * radius, (ref.sw / ref.ppu) * radius, (ref.sh / ref.ppu) * radius)
  return true
}

// ─── Disc ────────────────────────────────────────────────────────────────────

const discs = new Map<string, (HTMLCanvasElement | OffscreenCanvas) | null>()

/** Paint the disc's top face as a top-view circle of radius `r` at (c, c). */
export const paintDiscTop = (ctx: Ctx2D, c: number, r: number, rim: string) => {
  const outline = '#2a1a10'
  const wood = '#d9a86a'
  ctx.lineJoin = 'round'
  ctx.beginPath()
  ctx.arc(c, c, r * 0.97, 0, Math.PI * 2)
  ctx.fillStyle = rim
  ctx.fill()
  ctx.lineWidth = Math.max(1, r * 0.06)
  ctx.strokeStyle = outline
  ctx.stroke()
  // plush rim stitches
  ctx.setLineDash([r * 0.07, r * 0.06])
  ctx.beginPath()
  ctx.arc(c, c, r * 0.86, 0, Math.PI * 2)
  ctx.strokeStyle = mixHex(rim, '#ffffff', 0.55)
  ctx.lineWidth = Math.max(1, r * 0.03)
  ctx.stroke()
  ctx.setLineDash([])
  // wooden top
  ctx.beginPath()
  ctx.arc(c, c, r * 0.74, 0, Math.PI * 2)
  ctx.fillStyle = wood
  ctx.fill()
  ctx.lineWidth = Math.max(1, r * 0.035)
  ctx.strokeStyle = outline
  ctx.stroke()
  // spin marks: alternating wedges + tree rings so the turn reads
  for (let i = 0; i < 6; i++) {
    const a0 = (i / 6) * Math.PI * 2
    ctx.beginPath()
    ctx.moveTo(c, c)
    ctx.arc(c, c, r * 0.72, a0, a0 + Math.PI / 6)
    ctx.closePath()
    ctx.fillStyle = i % 2 ? '#c8935a' : '#e8bd84'
    ctx.fill()
  }
  ctx.strokeStyle = 'rgba(110, 66, 30, 0.55)'
  ctx.lineWidth = Math.max(1, r * 0.025)
  for (const k of [0.25, 0.45, 0.62]) {
    ctx.beginPath()
    ctx.arc(c, c, r * k, 0, Math.PI * 2)
    ctx.stroke()
  }
  // one bold team-colour arrow notch at the edge
  ctx.beginPath()
  ctx.moveTo(c + r * 0.74, c)
  ctx.lineTo(c + r * 0.5, c - r * 0.12)
  ctx.lineTo(c + r * 0.5, c + r * 0.12)
  ctx.closePath()
  ctx.fillStyle = rim
  ctx.fill()
  ctx.strokeStyle = outline
  ctx.lineWidth = Math.max(1, r * 0.025)
  ctx.stroke()
}

const discSprite = (rim: string, ppu: number) => {
  const key = `${rim}@${ppu}`
  let c = discs.get(key)
  if (c === undefined) {
    const size = Math.ceil(ppu * 2) + 4
    c = makeCanvas(size, size)
    const ctx = c ? (c.getContext('2d') as Ctx2D | null) : null
    if (c && ctx) paintDiscTop(ctx, size / 2, ppu, rim)
    else c = null
    if (discs.size > 48) discs.clear()
    discs.set(key, c)
  }
  return c
}

/**
 * Draw the turning disc: flat drop shadow → side band → rotating top face.
 * `radius` css px; `rotation` the blade's spin.
 */
export const drawSmasherDisc = (
  ctx: CanvasRenderingContext2D, x: number, y: number, radius: number, rotation: number, rim: string, deviceScale: number,
  shadow = true
) => {
  const sq = DISC_SQUASH
  const side = radius * DISC_THICKNESS * Math.sqrt(1 - sq * sq)
  if (shadow) {
    // flat drop shadow (no blur)
    ctx.fillStyle = 'rgba(20, 12, 6, 0.28)'
    ctx.beginPath()
    ctx.ellipse(x + radius * 0.1, y + side + radius * 0.12, radius * 1.06, radius * sq * 1.06, 0, 0, Math.PI * 2)
    ctx.fill()
  }
  // side band
  ctx.fillStyle = mixHex(rim, '#1a0e08', 0.45)
  ctx.strokeStyle = '#2a1a10'
  ctx.lineWidth = Math.max(1, radius * 0.06)
  ctx.beginPath()
  ctx.ellipse(x, y + side, radius * 0.97, radius * sq * 0.97, 0, 0, Math.PI)
  ctx.lineTo(x - radius * 0.97, y)
  ctx.ellipse(x, y, radius * 0.97, radius * sq * 0.97, 0, Math.PI, 0, true)
  ctx.closePath()
  ctx.fill()
  ctx.stroke()
  const sprite = discSprite(rim, atlasBucket(radius * deviceScale))
  if (!sprite) return
  const size = sprite.width
  const ppu = (size - 4) / 2
  ctx.save()
  ctx.translate(x, y)
  ctx.scale(1, sq)
  ctx.rotate(rotation)
  const k = radius / ppu
  ctx.drawImage(sprite, -size / 2 * k, -size / 2 * k, size * k, size * k)
  ctx.restore()
}

// ─── Portraits ───────────────────────────────────────────────────────────────

const PORTRAIT_PX = 192
/** Portrait yaw frame: a little turned, the classic 3/4 front. */
const PORTRAIT_FRAME = 1
const portraits = new Map<string, string>()

const fallbackPortrait = (id: SmasherId): string =>
  `data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10" data-smasher="${id}"><circle cx="5" cy="5" r="4" fill="#d9a86a"/></svg>`)}`

/** Cached data URL of a smasher on its disc (front 3/4), for DOM <img>s. */
export const smasherPortraitUrl = (smasherId?: SmasherId, modelId?: string, boss = false): string => {
  const id = smasherId ?? (modelId ? smasherForSkin(modelId) : 'bramble')
  const key = lookKey(id, modelId, boss)
  const hit = portraits.get(key)
  if (hit) return hit
  const c = makeCanvas(PORTRAIT_PX, PORTRAIT_PX)
  if (!c || !(c instanceof HTMLCanvasElement)) return fallbackPortrait(id)
  const ctx = c.getContext('2d')!
  // fit FRAME_BOX into the square
  const ppu = PORTRAIT_PX / Math.max(FRAME_W, FRAME_H) * 1.02
  const ox = PORTRAIT_PX / 2
  const oy = PORTRAIT_PX / 2 - ((FRAME_BOX.top + FRAME_BOX.bottom) / 2) * ppu
  drawSmasherDisc(ctx, ox, oy, ppu, 0.4, '#e0b04a', 1)
  const hi = paintedPortrait(id, modelId, boss)
  const p = hi && hasFrame(hi, PORTRAIT_FRAME) ? hi : paintedSheet(id, modelId, boss)
  if (p) drawPainted(ctx, p, PORTRAIT_FRAME, ox, oy, ppu)
  else drawSmasher(ctx, id, smasherPalette(id, modelId), frameYaw(PORTRAIT_FRAME), ox, oy, ppu, { boss })
  let url: string
  try {
    url = c.toDataURL('image/png')
  } catch {
    url = fallbackPortrait(id)
  }
  portraits.set(key, url)
  return url
}

// ─── Large portraits (VS intro) ──────────────────────────────────────────────
//
// The VS screen shows each smasher big — up to ~270 css px wide, on a 3×
// phone ~800 device px — far above the battle sheets' 64 ppu. Art, best first:
//  1. the hi-res PORTRAIT frames (portraits.mjs: the paintings' own ~254 px
//     cells, ~78 ppu) — at full layout size when they have the device px,
//  2. the battle SHEET frame, same rule,
//  3. otherwise the painting with the most px is drawn SMALLER — at exactly
//     its own ppu / dpr, i.e. 1:1 device px, never upscaled — as long as that
//     keeps ≥ PORTRAIT_MIN_FIT of the layout size (a 3× phone card needs
//     ~140–160 device ppu at a 168 css card: the portrait fits at ~0.5–0.6). Showing the
//     painted look a bit smaller beats falling back to the rig: the rig is a
//     different drawing from the one the battle then shows;
//  4. below that, the rig as vectors straight into the (css × dpr) canvas.
// The disc shrinks with the character, centred in the same box. Never drawn
// below the display's own pixel ratio.

/** Smallest fraction of the layout size the painted art may shrink to before the rig takes over. */
export const PORTRAIT_MIN_FIT = 0.4

export interface PortraitArtChoice<T> {
  art: T
  /** Drawn size / layout size (1, or < 1 when the art would otherwise be upscaled). */
  fit: number
}

/**
 * Pick the art for a portrait needing `cssPpu × deviceScale` device px per
 * unit from `candidates` (best first; null = not available): the first with
 * enough px at full size, else the one with the most px shrunk to 1:1 if that
 * keeps ≥ PORTRAIT_MIN_FIT, else null (draw the rig). Pure.
 */
export const choosePortraitArt = <T extends { ppu: number }>(
  candidates: readonly (T | null | undefined)[], cssPpu: number, deviceScale: number
): PortraitArtChoice<T> | null => {
  const need = cssPpu * deviceScale
  const avail = candidates.filter((c): c is T => !!c)
  for (const c of avail) if (c.ppu >= need) return { art: c, fit: 1 }
  let best: T | null = null
  for (const c of avail) if (!best || c.ppu > best.ppu) best = c
  if (!best || need <= 0) return null
  const fit = best.ppu / need
  return fit >= PORTRAIT_MIN_FIT ? { art: best, fit } : null
}

export interface PortraitDraw {
  kind: 'painted' | 'rig'
  /** Which art: the hi-res portrait, the battle sheet, or the rig. */
  art: 'portrait' | 'sheet' | 'rig'
  /** Drawn size / layout size. */
  fit: number
}

/**
 * Draw a smasher standing on its disc, disc centre at (x, y), `ppu` css px per
 * model unit, on a context already scaled by `deviceScale`. When the painted
 * art is drawn smaller (fit < 1) the whole portrait shrinks about the centre
 * of its frame box. Returns what was drawn (for the QA seam).
 */
export const drawSmasherPortrait = (
  ctx: CanvasRenderingContext2D, id: SmasherId, modelId: string | undefined, boss: boolean,
  frame: number, x: number, y: number, ppu: number, deviceScale: number, rim: string
): PortraitDraw => {
  const hi = paintedPortrait(id, modelId, boss)
  const pick = choosePortraitArt([hi && hasFrame(hi, frame) ? hi : null, paintedSheet(id, modelId, boss)], ppu, deviceScale)
  const fit = pick ? pick.fit : 1
  const mid = (FRAME_BOX.top + FRAME_BOX.bottom) / 2
  const u = ppu * fit
  y += mid * (ppu - u)
  const sq = DISC_SQUASH
  const side = u * DISC_THICKNESS * Math.sqrt(1 - sq * sq)
  ctx.fillStyle = 'rgba(20, 12, 6, 0.28)'
  ctx.beginPath()
  ctx.ellipse(x + u * 0.1, y + side + u * 0.12, u * 1.06, u * sq * 1.06, 0, 0, Math.PI * 2)
  ctx.fill()
  ctx.fillStyle = mixHex(rim, '#1a0e08', 0.45)
  ctx.strokeStyle = '#2a1a10'
  ctx.lineWidth = Math.max(1, u * 0.06)
  ctx.beginPath()
  ctx.ellipse(x, y + side, u * 0.97, u * sq * 0.97, 0, 0, Math.PI)
  ctx.lineTo(x - u * 0.97, y)
  ctx.ellipse(x, y, u * 0.97, u * sq * 0.97, 0, Math.PI, 0, true)
  ctx.closePath()
  ctx.fill()
  ctx.stroke()
  ctx.save()
  ctx.translate(x, y)
  ctx.scale(1, sq)
  ctx.rotate(0.4)
  paintDiscTop(ctx, 0, u, rim)
  ctx.restore()
  if (pick) {
    drawPainted(ctx, pick.art, frame, x, y, u)
    return { kind: 'painted', art: pick.art === hi ? 'portrait' : 'sheet', fit }
  }
  drawSmasher(ctx, id, smasherPalette(id, modelId), frameYaw(frame), x, y, u, { boss })
  return { kind: 'rig', art: 'rig', fit: 1 }
}

/**
 * Pre-draw the not-yet-drawn yaw frames of the battle sheets made most
 * recently (the looks on the board), until `budgetMs` of this call is spent.
 * The battle draws a frame lazily the first time a smasher turns to it; the
 * VS screen calls this in its quiet hold so the fight's first spins never
 * pay for it. Returns true while frames are left.
 */
export const warmSmasherSheets = (budgetMs: number, maxSheets = 12): boolean => {
  const t0 = typeof performance !== 'undefined' ? performance.now() : Date.now()
  const now = () => (typeof performance !== 'undefined' ? performance.now() : Date.now())
  const recent = [...sheets.values()].filter((s): s is Sheet => s !== null).slice(-maxSheets).reverse()
  // `drawn` is an int32 bitmask of the 32 frames (all set = 0xffffffff).
  const full = YAW_FRAMES >= 32 ? 0xffffffff : 2 ** YAW_FRAMES - 1
  for (const s of recent) {
    if ((s.drawn >>> 0) === full) continue
    for (let f = 0; f < YAW_FRAMES; f++) {
      if (now() - t0 >= budgetMs) return true
      ensureFrame(s, f)
    }
  }
  return false
}
