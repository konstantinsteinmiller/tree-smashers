/**
 * Persist a row, optimistically: an existing row only updates if nobody wrote
 * it since we read it (`updated_at` is strictly increasing), a new one only
 * inserts if it still does not exist. `false` = lost a race; the caller answers
 * 409 and the client retries.
 */
const writeRow = async (env: Env, r: LeagueRow, prevUpdatedAt: number | null, nowMs: number): Promise<boolean> => {
  const row = { ...r, updated_at: Math.max(nowMs, (prevUpdatedAt ?? 0) + 1) }
  const vals = COLS.map((c) => row[c])
  const res = prevUpdatedAt === null
    ? await env.DB
      .prepare(`INSERT INTO league (id, ${COLS.join(', ')}) VALUES (?${', ?'.repeat(COLS.length)}) ON CONFLICT(id) DO NOTHING`)
      .bind(row.id, ...vals)
      .run()
    : await env.DB
      .prepare(`UPDATE league SET ${COLS.map((c) => `${c} = ?`).join(', ')} WHERE id = ? AND updated_at = ?`)
      .bind(...vals, row.id, prevUpdatedAt)
      .run()
  return Number(res?.meta?.changes ?? 0) > 0
}

// ─── Tokens ─────────────────────────────────────────────────────────────────

const TOKEN_RE = /^v1\.(\d{1,15})\.(\d{1,10})\.([0-9a-f]{32})\.([0-9a-f]{64})$/

const hex = (bytes: Uint8Array): string => [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('')

const round4 = (e: number): number => Math.round(e * 10_000) / 10_000

const tokenMessage = (id: string, at: number, seed: number, nonce: string, opp: string, E: number): string =>
  `league:v1:${id}:${at}:${seed}:${nonce}:${opp}:${E}`

const mintToken = async (secret: string, id: string, at: number, opp: string, E: number): Promise<{ token: string; seed: number }> => {
  const rnd = crypto.getRandomValues(new Uint8Array(20))
  const seed = ((rnd[0]! << 24) | (rnd[1]! << 16) | (rnd[2]! << 8) | rnd[3]!) >>> 0 || 1
  const nonce = hex(rnd.slice(4))
  const sig = await hmac(secret, tokenMessage(id, at, seed, nonce, opp, E))
  return { token: `v1.${at}.${seed}.${nonce}.${sig}`, seed }
}

/** Check a token against the pending battle it claims to be; its seed on success. */
const verifyToken = async (secret: string, token: string, r: LeagueRow): Promise<number | null> => {
  const m = TOKEN_RE.exec(token)
  if (!m || r.pend_at === null || r.pend_opp === null || r.pend_e === null) return null
  const at = Number(m[1])
  const seed = Number(m[2])
  if (at !== r.pend_at) return null
  const expected = await hmac(secret, tokenMessage(r.id, at, seed, m[3]!, r.pend_opp, r.pend_e))
  return safeEqual(m[4]!, expected) ? seed : null
}

const seedOf = (token: string): number => Number(TOKEN_RE.exec(token)?.[2] ?? 0)

// ─── Opponents ──────────────────────────────────────────────────────────────

const noSkills = (b: PlayerBuildV1): PlayerBuildV1 => ({ ...b, sk: [] })

const storedBuild = (raw: unknown): PlayerBuildV1 | null => {
  if (typeof raw !== 'string' || raw.length === 0) return null
  try {
    return validatePlayerBuildShape(JSON.parse(raw))
  } catch {
    return null
  }
}

const POOL_ID_RE = /^p:(\d{1,15})$/

type OppSpec =
  | { kind: 'npc'; key: string }
  | { kind: 'player'; key: string; rowid: number }
  | { kind: 'gate'; key: string; tier: LeagueTier }

/** Rankable opponents are pool rows (`p:<rowid>`) and NPCs (`npc:…`) only —
 *  a baked-pool card (`bake:<hash>`), a raw player id or anything else is
 *  practice at best and is refused (400). */
const parseOpp = (body: Record<string, unknown>): OppSpec | null => {
  if (body.gateTier !== undefined && body.gateTier !== null) {
    const t = body.gateTier
    if (typeof t !== 'string' || !(LEAGUE_TIERS as readonly string[]).includes(t) || t === 'wood') return null
    return { kind: 'gate', key: `gate:${t}`, tier: t as LeagueTier }
  }
  const opp = body.opp
  if (parseNpcId(opp) !== null) return { kind: 'npc', key: opp as string }
  const m = typeof opp === 'string' ? POOL_ID_RE.exec(opp) : null
  if (m) return { kind: 'player', key: opp as string, rowid: Number(m[1]) }
  return null
}

/** Power window [lo, hi] of a pool band, in whole team power. */
export const poolWindow = (band: number): [number, number] => {
  const c = band * POOL_BAND_WIDTH
  return [
    Math.max(0, Math.floor((c + LEAGUE_POWER_OFFSET) * POOL_LO - LEAGUE_POWER_OFFSET)),
    Math.ceil((c + LEAGUE_POWER_OFFSET) * POOL_HI - LEAGUE_POWER_OFFSET)
  ]
}

interface PoolEntry {
  id: string
  name: string
  build: PlayerBuildV1
  lpower: number
}

/** A pool entry as CACHED (server-side only: D1 league_cache + the edge). The
 *  owner's real id rides along so a caller can be dropped from their own
 *  pool, and is stripped from every response (`publicPool`). */
interface CachedPoolEntry extends PoolEntry {
  sid: string
}

const poolEntry = (r: { rid: unknown; name: unknown; build: unknown }): PoolEntry | null => {
  const build = storedBuild(r.build)
  if (!build) return null
  return {
    id: `p:${int(r.rid)}`,
    name: sanitizeDisplayName(cleanName(r.name)),
    build,
    lpower: buildPower(build)
  }
}

interface CachedPool {
  band: number
  lo: number
  hi: number
  updatedAt: number
  entries: CachedPoolEntry[]
}

/** The response form of a cached pool: the caller's own row dropped, every
 *  owner id stripped. */
const publicPool = (callerId: string | null) => (pool: CachedPool) => ({
  ...pool,
  entries: pool.entries
    .filter((e) => e.sid !== callerId)
    .map(({ id, name, build, lpower }) => ({ id, name, build, lpower }))
})

// ─── Caches ─────────────────────────────────────────────────────────────────

/** The edge cache, or null where there is none (tests, some local runs). */
const edge = (): Cache | null =>
  typeof caches !== 'undefined' && (caches as { default?: Cache }).default ? (caches as { default: Cache }).default : null

/**
 * A materialised read from `league_cache`: fresh → served; stale or missing →
 * rebuilt and written; the rebuild failing with a stale row present → the stale
 * row is served (D1 reads may still work when the rebuild's query or write
 * does not). Throws only when there is nothing at all to serve.
 */
const materialised = async <T>(env: Env, id: string, ttlMs: number, rebuild: () => Promise<T>): Promise<T> => {
  const row = await env.DB
    .prepare('SELECT json, updated_at FROM league_cache WHERE id = ?')
    .bind(id)
    .first<{ json: string; updated_at: number }>()
  let cached: T | null = null
  if (row?.json) {
    try {
      cached = JSON.parse(row.json) as T
    } catch { /* rebuild */
    }
  }
  if (cached !== null && Date.now() - int(row?.updated_at) < ttlMs) return cached
  try {
    const fresh = await rebuild()
    await env.DB
      .prepare(
        'INSERT INTO league_cache (id, json, updated_at) VALUES (?, ?, ?)\n' +
        'ON CONFLICT(id) DO UPDATE SET json = excluded.json, updated_at = excluded.updated_at'
      )
      .bind(id, JSON.stringify(fresh), Date.now())
      .run()
    return fresh
  } catch (e) {
    if (cached !== null) return cached
    throw e
  }
}

/**
 * GET with the edge in front: a hit is free; a miss builds, stores the fresh
 * copy (`ttl` s) plus a day-long emergency copy; a build that throws serves the
 * emergency copy, else 503.
 */
const edgeCached = async <T>(
  url: URL, cors: Record<string, string>, ttl: number, build: () => Promise<T>,
  shape?: (body: T) => unknown
): Promise<Response> => {
  const cache = edge()
  const key = new Request(new URL(url.pathname + url.search, url.origin).toString(), { method: 'GET' })
  const staleUrl = new URL(url.pathname + '-stale' + url.search, url.origin)
  const staleKey = new Request(staleUrl.toString(), { method: 'GET' })
  if (cache) {
    const hit = await cache.match(key)
    if (hit) return shape ? json(shape(await hit.json() as T), 200, { ...cors, 'cache-control': `public, max-age=${ttl}` }) : withCors(hit, cors)
  }
  try {
    const body = await build()
    const fresh = json(body, 200, { 'cache-control': `public, max-age=${ttl}` })
    if (cache) {
      await cache.put(key, fresh.clone())
      await cache.put(staleKey, json(body, 200, { 'cache-control': `public, max-age=${STALE_TTL}` }))
    }
    return shape ? json(shape(body), 200, { ...cors, 'cache-control': `public, max-age=${ttl}` }) : withCors(fresh, cors)
  } catch {
    const stale = cache ? await cache.match(staleKey) : undefined
    if (stale) {
      return shape
        ? json(shape(await stale.json() as T), 200, { ...cors, 'x-league-stale': '1' })
        : withCors(stale, cors, { 'x-league-stale': '1' })
    }
    return json({ error: 'unavailable' }, 503, cors)
  }
}

// ─── GET routes ─────────────────────────────────────────────────────────────

const buildPool = async (env: Env, band: number): Promise<CachedPool> => {
  const [lo, hi] = poolWindow(band)
  const step = (hi - lo + 1) / 3
  const cuts = [lo, Math.floor(lo + step), Math.floor(lo + 2 * step), hi + 1]
  // Three index range scans (idx_scores_lpower, partial on build IS NOT NULL),
  // each stopping after POOL_PER_THIRD rows — the pool spreads over easier /
  // even / harder instead of filling up from the bottom of the window.
  const third = 'SELECT * FROM (SELECT rowid AS rid, id AS sid, name, build, lpower FROM scores ' +
    'WHERE build IS NOT NULL AND lpower >= ? AND lpower < ? ORDER BY lpower, build_at DESC LIMIT ?)'
  const { results } = await env.DB
    .prepare(`${third} UNION ALL ${third} UNION ALL ${third}`)
    .bind(cuts[0], cuts[1], POOL_PER_THIRD, cuts[1], cuts[2], POOL_PER_THIRD, cuts[2], cuts[3], POOL_PER_THIRD)
    .all<{ rid: number; sid: string; name: string; build: string; lpower: number }>()
  const entries: CachedPoolEntry[] = []
  for (const r of results ?? []) {
    const e = poolEntry(r)
    if (e) entries.push({ ...e, sid: String(r.sid) })
  }
  return { band, lo, hi, updatedAt: Date.now(), entries }
}

const buildExport = async (env: Env) => {
  const { results } = await env.DB
    .prepare(
      'SELECT rowid AS rid, name, build, lpower FROM scores WHERE build IS NOT NULL AND lpower IS NOT NULL ' +
      'ORDER BY lpower, build_at DESC LIMIT ?'
    )
    .bind(EXPORT_SCAN)
    .all<{ rid: number; name: string; build: string; lpower: number }>()
  const perBand = new Map<number, number>()
  const entries: PoolEntry[] = []
  for (const r of results ?? []) {
    const e = poolEntry(r)
    if (!e) continue
    const b = Math.round(e.lpower / POOL_BAND_WIDTH)
    const n = perBand.get(b) ?? 0
    if (n >= EXPORT_PER_BAND) continue
    perBand.set(b, n + 1)
    entries.push(e)
  }
  return { v: 1, updatedAt: Date.now(), bandWidth: POOL_BAND_WIDTH, entries }
}

/** LP histogram bucket: the division floor below Champion, the exact LP from it. */
const lpBucket = (lp: number): number => (lp >= CHAMPION_LP ? lp : lp - (lp % LP_PER_DIVISION))

const buildTop = async (env: Env, season: number) => {
  const { results } = await env.DB
    .prepare('SELECT name, lp FROM league WHERE season = ? ORDER BY lp DESC, updated_at ASC LIMIT ?')
    .bind(season, TOP_N)
    .all<{ name: string; lp: number }>()
  let rank = 0
  let prev: number | null = null
  const entries = (results ?? []).map((r, i) => {
    const lp = int(r.lp)
    if (prev === null || lp < prev) rank = i + 1
    prev = lp
    const pos = tierOf(lp)
    return { rank, name: sanitizeDisplayName(cleanName(r.name)), lp, tier: pos.tier, division: pos.division }
  })
  let dist: [number, number][]
  if (entries.length < TOP_N) {
    // The rows ARE the season — derive the histogram for free (see /top).
    const counts = new Map<number, number>()
    for (const e of entries) counts.set(lpBucket(e.lp), (counts.get(lpBucket(e.lp)) ?? 0) + 1)
    dist = [...counts.entries()].sort((a, b) => b[0] - a[0])
  } else {
    dist = await materialised(env, `lpdist:${season}`, LP_DIST_TTL_MS, async () => {
      const { results: rows } = await env.DB
        .prepare(
          'SELECT CASE WHEN lp >= ? THEN lp ELSE lp - (lp % ?) END AS b, COUNT(*) AS n ' +
          'FROM league WHERE season = ? GROUP BY b ORDER BY b DESC'
        )
        .bind(CHAMPION_LP, LP_PER_DIVISION, season)
        .all<{ b: number; n: number }>()
      return (rows ?? []).map((r) => [int(r.b), int(r.n)] as [number, number])
    })
  }
  const total = Math.max(dist.reduce((s, [, n]) => s + n, 0), entries.length)
  return { season, updatedAt: Date.now(), total, entries, dist }
}

// ─── POST routes ────────────────────────────────────────────────────────────

const readBody = async (request: Request): Promise<Record<string, unknown> | null> => {
  try {
    const b = await request.json()
    return typeof b === 'object' && b !== null && !Array.isArray(b) ? b as Record<string, unknown> : null
  } catch {
    return null
  }
}

const start = async (request: Request, env: Env, cors: Record<string, string>, secret: string): Promise<Response> => {
  const body = await readBody(request)
  if (!body) return json({ error: 'bad json' }, 400, cors)
  const id = body.id
  if (!validId(id)) return json({ error: 'bad id' }, 400, cors)
  const posted = validatePlayerBuildShape(body.build)
  if (!posted) return json({ error: 'bad build' }, 400, cors)
  const opp = parseOpp(body)
  if (!opp) return json({ error: 'bad opp' }, 400, cors)
  const caps = typeof body.caps === 'object' && body.caps !== null ? body.caps as Record<string, unknown> : {}
  const skills = caps.skills !== false
  const own = skills ? posted : noSkills(posted)
  const ownPower = buildPower(own)
  const name = cleanName(body.name)
  const now = Date.now()

  // ONE read: the player's league row and (for a pool opponent) the
  // opponent's scores row, joined on a one-row literal so both may be absent.
  const joined = await env.DB
    .prepare(
      'SELECT l.*, s.id AS opp_id, s.name AS opp_name, s.build AS opp_build ' +
      'FROM (SELECT ? AS pid, ? AS oprow) q ' +
      'LEFT JOIN league l ON l.id = q.pid LEFT JOIN scores s ON s.rowid = q.oprow'
    )
    .bind(id, opp.kind === 'player' ? opp.rowid : null)
    .first<Record<string, unknown>>()
  const exists = joined !== null && typeof joined.id === 'string'
  const prevUpdatedAt = exists ? int(joined!.updated_at) : null
  let row = exists ? rowFrom(joined!) : freshRow(id, name, now)
  // A refusal only writes when something was actually settled or rolled —
  // never a fresh, empty row.
  let dirty = false
  let abandoned: (ReturnType<typeof outcomeView> & { reason: 'expired' | 'abandoned' }) | null = null

  // A battle already in flight.
  if (row.pend_tok !== null && row.pend_at !== null) {
    if (now - row.pend_at > TOKEN_TTL_MS) {
      const s = settleExpired(row)
      row = s.row
      abandoned = { ...outcomeView(s.outcome), reason: 'expired' }
    } else if (row.pend_opp === opp.key) {
      // The same fight asked for again (a retried request whose answer was
      // lost): hand back the SAME battle, no write, no second fight counted.
      const oppBuild = await resolveOpp(opp, joined, skills, id)
      if ('error' in oppBuild) return json({ error: oppBuild.error, state: view(advance(row, now)) }, oppBuild.status, cors)
      return json({
        token: row.pend_tok, seed: seedOf(row.pend_tok), E: row.pend_e, ownPower,
        opp: oppBuild.opp, gate: opp.kind === 'gate' ? opp.tier : null,
        expiresAt: row.pend_at + TOKEN_TTL_MS, minResultAt: row.pend_at + MIN_BATTLE_MS,
        state: view(advance(row, now)), abandoned: null, resumed: true
      }, 200, cors)
    } else {
      // A different fight while one is open: the open one was abandoned (O10).
      const s = settle(row, 'loss', row.pend_e ?? 0.5, now)
      row = s.row
      abandoned = { ...outcomeView(s.outcome), reason: 'abandoned' }
    }
    dirty = true
  }
  const rolled = advance(row, now)
  if (JSON.stringify(rolled) !== JSON.stringify(row)) dirty = true
  row = { ...rolled, name }

  /** Refuse the fight, persisting whatever was already settled above. */
  const refuse = async (status: number, payload: Record<string, unknown>): Promise<Response> => {
    if (dirty && !(await writeRow(env, row, prevUpdatedAt, now))) return json({ error: 'busy' }, 409, cors)
    return json({ ...payload, state: view(row), abandoned }, status, cors)
  }

  if (row.fights >= SERVER_DAILY_CAP) return refuse(429, { error: 'daily cap' })
  const atGate = atPromotionGate(row.lp)
  if (opp.kind === 'gate') {
    if (!atGate || nextTier(row.lp) !== opp.tier) return refuse(409, { error: 'not at gate' })
  } else if (atGate) {
    return refuse(409, { error: 'gate', gateTier: nextTier(row.lp) })
  }
  const resolved = await resolveOpp(opp, joined, skills, id)
  if ('error' in resolved) return refuse(resolved.status, { error: resolved.error })

  const E = resolved.opp === null ? 0.5 : round4(expectedScore(ownPower, resolved.opp.power))
  const { token, seed } = await mintToken(secret, id, now, opp.key, E)
  row = { ...row, fights: row.fights + 1, pend_tok: token, pend_at: now, pend_opp: opp.key, pend_e: E }
  if (!(await writeRow(env, row, prevUpdatedAt, now))) return json({ error: 'busy' }, 409, cors)
  return json({
    token, seed, E, ownPower,
    opp: resolved.opp, gate: opp.kind === 'gate' ? opp.tier : null,
    expiresAt: now + TOKEN_TTL_MS, minResultAt: now + MIN_BATTLE_MS,
    state: view(row), abandoned, resumed: false
  }, 200, cors)
}

type ResolvedOpp =
  | { opp: { id: string; name: string; build: PlayerBuildV1; power: number } | null }
  | { error: string; status: number }

/** The opponent's build and power, recomputed server-side — never the client's. */
const resolveOpp = async (
  opp: OppSpec, joined: Record<string, unknown> | null, skills: boolean, selfId: string
): Promise<ResolvedOpp> => {
  if (opp.kind === 'gate') return { opp: null }
  if (opp.kind === 'npc') {
    const build = npcBuildFromId(opp.key, { skills })
    if (!build) return { error: 'bad opp', status: 400 }
    return { opp: { id: opp.key, name: generatedOpponentName(opp.key), build, power: buildPower(build) } }
  }
  if (joined?.opp_id === selfId) return { error: 'self', status: 409 }
  const stored = storedBuild(joined?.opp_build)
  if (!stored) return { error: 'opp gone', status: 404 }
  const build = skills ? stored : noSkills(stored)
  return {
    opp: { id: opp.key, name: sanitizeDisplayName(cleanName(joined?.opp_name)), build, power: buildPower(build) }
  }
}

const result = async (request: Request, env: Env, cors: Record<string, string>, secret: string): Promise<Response> => {
  const body = await readBody(request)
  if (!body) return json({ error: 'bad json' }, 400, cors)
  const { id, token } = body
  const res = body.result
  if (!validId(id)) return json({ error: 'bad id' }, 400, cors)
  if (typeof token !== 'string' || token.length > 200) return json({ error: 'bad token' }, 401, cors)
  if (res !== 'win' && res !== 'loss') return json({ error: 'bad result' }, 400, cors)
  const now = Date.now()

  const raw = await env.DB.prepare('SELECT * FROM league WHERE id = ?').bind(id).first<Record<string, unknown>>()
  if (!raw) return json({ error: 'no pending' }, 409, cors)
  const row = rowFrom(raw)
  if (row.pend_tok === null || row.pend_at === null) return json({ error: 'no pending', state: view(advance(row, now)) }, 409, cors)
  if (!safeEqual(token, row.pend_tok) || (await verifyToken(secret, token, row)) === null) {
    return json({ error: 'bad token' }, 401, cors)
  }

  /** Persist a settled battle, but only while THIS token is still the pending one. */
  const commit = async (next: LeagueRow): Promise<boolean> => {
    const r = await env.DB
      .prepare(`UPDATE league SET ${COLS.map((c) => `${c} = ?`).join(', ')} WHERE id = ? AND pend_tok = ?`)
      .bind(...COLS.map((c) => (c === 'updated_at' ? Math.max(now, row.updated_at + 1) : next[c])), id, token)
      .run()
    return Number(r?.meta?.changes ?? 0) > 0
  }

  const age = now - row.pend_at
  if (age > TOKEN_TTL_MS) {
    // Too late to count as played — it is the abandoned-fight loss (O10), now.
    const s = settleExpired(row)
    const next = advance(s.row, now)
    if (!(await commit(next))) return json({ error: 'no pending' }, 409, cors)
    return json({ error: 'expired', state: view(next), ...outcomeView(s.outcome) }, 410, cors)
  }
  // A loss may be reported at once (surrender); a win needs a real fight.
  if (res === 'win' && age < MIN_BATTLE_MS) return json({ error: 'too fast' }, 422, cors)
  if (body.durationMs !== undefined) {
    const d = Number(body.durationMs)
    if (!Number.isFinite(d) || d < 0 || d > age + DURATION_SLACK_MS) return json({ error: 'bad duration' }, 422, cors)
  }

  const s = settle(row, res, row.pend_e ?? 0.5, now)
  if (!(await commit(s.row))) return json({ error: 'no pending' }, 409, cors)
  return json({ state: view(s.row), ...outcomeView(s.outcome) }, 200, cors)
}

const me = async (env: Env, url: URL, cors: Record<string, string>): Promise<Response> => {
  const id = url.searchParams.get('id')
  if (!validId(id)) return json({ error: 'bad id' }, 400, cors)
  const now = Date.now()
  const joined = await env.DB
    .prepare(
      'SELECT l.*, s.rowid AS pool_rid FROM (SELECT ? AS pid) q ' +
      'LEFT JOIN league l ON l.id = q.pid LEFT JOIN scores s ON s.id = q.pid'
    )
    .bind(id)
    .first<Record<string, unknown>>()
  const exists = joined !== null && typeof joined.id === 'string'
  // Read-only: the lazy reset is SHOWN here and WRITTEN by the next /start.
  const row = advance(exists ? rowFrom(joined!) : freshRow(id, 'Anon', now), now)
  const rid = joined?.pool_rid
  return json(
    { exists, state: view(row), poolId: rid == null ? null : `p:${int(rid)}`, season: seasonIndex(now) },
    200,
    { ...cors, 'cache-control': 'no-store' }
  )
}

// ─── Router ─────────────────────────────────────────────────────────────────

export const handleLeague = async (
  request: Request, env: Env, url: URL, cors: Record<string, string>
): Promise<Response> => {
  const path = url.pathname
  try {
    if (request.method === 'GET') {
      if (path === '/league/pool') {
        const band = Number(url.searchParams.get('band'))
        if (!Number.isInteger(band) || band < 0 || band > POOL_MAX_BAND) return json({ error: 'bad band' }, 400, cors)
        // Optional caller id: their own row is dropped from the answer (they
        // cannot recognise it — pool ids are `p:<rowid>`, never player ids).
        const caller = url.searchParams.get('id')
        if (caller !== null && !validId(caller)) return json({ error: 'bad id' }, 400, cors)
        // Canonical cache key: only `band` (never the caller), so one cached
        // pool serves everybody and `?band=5&x=1` cannot bust it.
        const key = new URL(`/league/pool?band=${band}`, url.origin)
        return edgeCached(key, cors, EDGE_TTL,
          () => materialised(env, `pool:${band}`, POOL_TTL_MS, () => buildPool(env, band)),
          publicPool(caller))
      }
      if (path === '/league/top') {
        const season = seasonIndex(Date.now())
        return edgeCached(new URL('/league/top', url.origin), cors, EDGE_TTL,
          () => materialised(env, `top:${season}`, TOP_TTL_MS, () => buildTop(env, season)))
      }
      if (path === '/league/pool-export') {
        return edgeCached(new URL('/league/pool-export', url.origin), cors, EXPORT_EDGE_TTL,
          () => materialised(env, 'export', EXPORT_TTL_MS, () => buildExport(env)))
      }
      if (path === '/league/me') return await me(env, url, cors)
    }
    if (request.method === 'POST' && (path === '/league/start' || path === '/league/result')) {
      // Tokens need the server secret; without it the league cannot be played
      // (pool / top / me still answer). Same vocabulary as a D1 outage.
      const secret = env.LEAGUE_SECRET
      if (!secret) return json({ error: 'league offline' }, 503, cors)
      return await (path === '/league/start' ? start(request, env, cors, secret) : result(request, env, cors, secret))
    }
    return json({ error: 'not found' }, 404, cors)
  } catch {
    // D1 refused (quota, outage). A 503 in JSON, never an unhandled 1101.
    return json({ error: 'unavailable' }, 503, cors)
  }
}
