const stateOf = (r: LeagueRow): LeagueMathState => ({
  season: r.season,
  lp: r.lp,
  peakLp: r.peak_lp,
  streak: r.streak,
  shields: r.shields,
  day: r.day,
  dayGain: r.gained,
  battles: r.wins + r.losses
})

/** Write a leagueMath state back onto a row (derived columns included). */
const withState = (r: LeagueRow, s: LeagueMathState): LeagueRow => ({
  ...r,
  season: s.season,
  lp: s.lp,
  peak_lp: s.peakLp,
  streak: s.streak,
  shields: s.shields,
  day: s.day,
  gained: s.dayGain,
  floor: seasonFloorLp(s.peakLp),
  // best ever: the row's own peak counts too (a season reset lowers peak_lp)
  best_tier: Math.max(r.best_tier, tierIdx(tierOf(r.peak_lp).tier), tierIdx(tierOf(s.peakLp).tier))
})

/**
 * Bring a row to `nowMs` (the LAZY reset): leagueMath.rollover does the season
 * reset and clears the day's LP gain; this clears the season's win/loss count,
 * the day's fight count, and remembers the finished season for /league/me.
 */
const advance = (r: LeagueRow, nowMs: number): LeagueRow => {
  const { state, ended } = rollover(stateOf(r), nowMs)
  let out = withState(r, state)
  if (state.season !== r.season) out = { ...out, wins: 0, losses: 0 }
  if (state.day !== r.day) out = { ...out, fights: 0 }
  if (ended) out = { ...out, last_season: ended.season, last_tier: tierIdx(ended.peakTier) }
  return out
}

const clearPending = (r: LeagueRow): LeagueRow => ({ ...r, pend_tok: null, pend_at: null, pend_opp: null, pend_e: null })

/** Apply one battle to a row at `nowMs` (rolls it first). Clears the pending. */
const settle = (r: LeagueRow, result: 'win' | 'loss', E: number, nowMs: number): { row: LeagueRow; outcome: BattleOutcome } => {
  const rolled = advance(r, nowMs)
  const outcome = applyBattle(stateOf(rolled), { result, E }, nowMs)
  const row = clearPending(withState({
    ...rolled,
    wins: rolled.wins + (result === 'win' ? 1 : 0),
    losses: rolled.losses + (result === 'loss' ? 1 : 0)
  }, outcome.state))
  return { row, outcome }
}

/** The pending battle's own expiry: it is settled AS OF then, not as of now. */
const settleExpired = (r: LeagueRow): { row: LeagueRow; outcome: BattleOutcome } =>
  settle(r, 'loss', r.pend_e ?? 0.5, (r.pend_at ?? 0) + TOKEN_TTL_MS)

const nextTier = (lp: number): LeagueTier | null => {
  const i = tierIdx(tierOf(lp).tier)
  return i >= 0 && i < LEAGUE_TIERS.length - 1 ? (LEAGUE_TIERS[i + 1] as LeagueTier) : null
}

