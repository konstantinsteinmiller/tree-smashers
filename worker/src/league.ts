/**
 * ─── Tree Smashers league routes (LG4) ────────────────────────────────────────
 *
 * The server half of the simulated-PvP league. Every rule (tiers, LP deltas,
 * floors, shields, the gatekeeper gate, the daily LP cap, season resets) lives
 * in the worker-shared `src/league/leagueMath.ts`; this file only decides WHO
 * may fight WHOM, and when, and persists the outcome. It never re-implements a
 * rule.
 *
 *   GET  /league/pool?band=N[&id=]  opponents near team power
 *                             N × POOL_BAND_WIDTH (real players' posted builds;
 *                             cached 10 min in D1 + 60 s at the edge; stale
 *                             copy on D1 failure); the caller's own row dropped
 *   GET  /league/me?id=       the player's standing, lazily rolled to today
 *   GET  /league/top          this season's top 100 + LP histogram (5 min)
 *   POST /league/start        opens ONE battle: recomputes both powers, returns
 *                             an HMAC token, the battle seed and E
 *   POST /league/result       closes it: token checks, then applyBattle
 *   GET  /league/pool-export  the whole pool, thinned per band (bake script)
 *
 * Anti-abuse: the client's powers, E and opponent build are never trusted —
 * the server recomputes them from the posted build (structurally validated),
 * the opponent's STORED build or the NPC id (regenerated by leagueNpc). A
 * battle token is single-use, lives MIN_BATTLE_MS…TOKEN_TTL_MS, and a battle
 * that is never reported (closed tab, surrender without a post, a second
 * /start) counts as a LOSS (plan O10). Opponent rows are only ever READ.
 *
 * Privacy: a player's `id` is their only credential, so it is never
 * published. Pool opponents are addressed as `p:<scores rowid>` instead.
 *
 * Quota per fight: /start = 1 read statement (league row JOIN opponent row) +
 * ≤ 1 write; /result = 1 read + 1 write. Every D1 failure answers 503 (never a
 * thrown 1101).
 */

