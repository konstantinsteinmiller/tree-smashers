/** Team power per pool band: band N is centred on power N × 10. */
export const POOL_BAND_WIDTH = 10
export const POOL_MAX_BAND = Math.ceil(NPC_MAX_POWER / POOL_BAND_WIDTH)
/**
 * A band's window, as factors on (power + P0) — the space expectedScore works
 * in. The client's three cards aim at E 0.65 / 0.5 / 0.35, i.e. factors
 * ≈ 0.91 / 1 / 1.10 around its base power; 0.85…1.18 covers all three with
 * room for the band's rounding.
 */
const POOL_LO = 0.85
const POOL_HI = 1.18
/** Rows per third of the window (easier / even / harder). */
const POOL_PER_THIRD = 16
const POOL_TTL_MS = 10 * 60_000
const TOP_N = 100
const TOP_TTL_MS = 5 * 60_000
/** The histogram scans the season's rows — hourly, like the board's `dist`. */
const LP_DIST_TTL_MS = 60 * 60_000
const EXPORT_TTL_MS = 60 * 60_000
/** Rows the export reads at most, and keeps per band. */
const EXPORT_SCAN = 3000
const EXPORT_PER_BAND = 8
/** Seconds the edge serves a cached read, and keeps an emergency copy. */
const EDGE_TTL = 60
const EXPORT_EDGE_TTL = 3600
const STALE_TTL = 86_400
/** A client's durationMs may exceed the server-measured age by this (clock
 *  granularity); more than that is a lie. */
const DURATION_SLACK_MS = 2_000

