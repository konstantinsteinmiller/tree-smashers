#!/usr/bin/env node
/**
 * PAINT-STATUS.md for the Art Desk's sheets folder — which sheets still need
 * painting (art-generation-pipeline STATUS.md, the four marks), plus, for the
 * boss drawables, what the game actually SHIPS at the target path:
 *
 *   procedural  the baked fallback drawing (art/bosses/painters.mjs) — needs painting
 *   painted     a sliced painting replaced it
 *   missing     nothing at the target (run node art/bosses/build.mjs)
 *
 *   node art/bosses/status.mjs            rewrite art-sheets/PAINT-STATUS.md, print the summary
 *   node art/bosses/status.mjs --print    print only
 *
 * A report, not a contract: re-run it after painting or slicing anything.
 * `bossPaintStatus(root)` is the same answer as data (tests/bossArt.test.ts).
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { loadConfig } from '../../tools/art-desk/config.mjs'
import { scanJobs } from '../../tools/art-desk/jobs.mjs'
import { DRAWABLES, PROCEDURAL_RECEIPT, STATUS_DOC } from './manifest.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')

const sha = (file) => createHash('sha1').update(readFileSync(file)).digest('hex').slice(0, 12)
const readJson = (file, fallback) => {
  try {
    return JSON.parse(readFileSync(file, 'utf-8'))
  } catch {
    return fallback
  }
}

/** What ships at a drawable's target: 'procedural' | 'painted' | 'missing'. */
export const shippedState = (root, target, receipt = readJson(join(root, PROCEDURAL_RECEIPT), {})) => {
  const file = join(root, 'public', target)
  if (!existsSync(file)) return 'missing'
  return receipt[target] && receipt[target] === sha(file) ? 'procedural' : 'painted'
}

/**
 * One row per Art Desk job (every `PROMPTS-*.md`), boss drawables carrying
 * their shipped state. `needsPainting` is true for a boss drawable until a
 * painting both exists in painted/ with a current receipt AND replaced the
 * procedural file at its target.
 */
export const bossPaintStatus = (root = ROOT) => {
  const cfg = loadConfig(root)
  const jobs = scanJobs(cfg)
  const receipt = readJson(join(root, PROCEDURAL_RECEIPT), {})
  const rows = jobs.map((j) => ({
    stem: j.stem,
    title: j.title,
    doc: j.doc,
    ref: j.ref,
    rev: j.rev,
    mark: j.mark,
    state: j.state,
    drawable: null,
    shipped: null,
    needsPainting: j.mark !== '✓'
  }))
  for (const d of DRAWABLES) {
    let row = rows.find((r) => r.stem.toLowerCase() === d.stem.toLowerCase())
    if (!row) {
      row = {
        stem: d.stem,
        title: d.title,
        doc: null,
        ref: null,
        rev: null,
        mark: '·',
        state: 'no prompt block yet — run node art/bosses/build.mjs',
        drawable: null,
        shipped: null,
        needsPainting: true
      }
      rows.push(row)
    }
    row.drawable = d
    row.shipped = shippedState(root, d.target, receipt)
    row.needsPainting = row.shipped !== 'painted' || row.mark !== '✓'
  }
  return rows
}

export const renderStatus = (rows) => {
  const count = (m) => rows.filter((r) => r.mark === m).length
  const need = rows.filter((r) => r.needsPainting).length
  const lines = [
    '# Paint status (generated by art/bosses/status.mjs — do not edit by hand)',
    '',
    `**${count('✓')} sliced · ${count('!')} need a repaint · ${count('?')} painted, unreceipted · ${count('·')} outstanding** — ${need} need painting`,
    '',
    '| | Sheet | Prompt block in | Reference | State | Ships at target |',
    '|---|---|---|---|---|---|'
  ]
  for (const r of rows) {
    const ref = r.ref ? `\`${r.ref}\`${r.rev ? ` (rev \`${r.rev}\`)` : ''}` : '—'
    const ships = r.drawable
      ? `\`public/${r.drawable.target}\` — ${r.shipped === 'procedural' ? 'procedural fallback, NEEDS PAINTING' : r.shipped === 'painted' ? 'painted' : 'MISSING'}`
      : '—'
    lines.push(`| ${r.mark} | ${r.title} (\`${r.stem}\`) | ${r.doc ? `\`${r.doc}\`` : '—'} | ${ref} | ${r.needsPainting && r.mark === '✓' ? 'sliced, but the target is still the procedural drawing' : r.state} | ${ships} |`)
  }
  lines.push('', 'Marks: ✓ sliced and current · ! repaint (reference changed / old painting parked) · ? painted, no receipt · · not painted yet.', '')
  lines.push(...arenaArtStatus(ROOT))
  return lines.join('\n')
}

/** Arena floors / backdrop / props (text-only paint pass) — read from disk. */
const arenaArtStatus = (root) => {
  let files = []
  try {
    files = readdirSync(join(root, 'art-sheets', 'painted'))
  } catch {
  }
  const floors = files.map(f => /^arena-floor-(\d+)\.png$/.exec(f)?.[1]).filter(Boolean).map(Number).sort((a, b) => a - b)
  const props = files.map(f => /^props-(.+)\.png$/.exec(f)?.[1]).filter(Boolean)
  return [
    '## Arena art (floors, backdrop, props)',
    '',
    '> **Gemini account limitation (since the Oct 2026 account switch):** this account REFUSES reference-based edits',
    '> ("Sorry, I can\'t edit images for you yet. Can I generate an image instead") — paint with TEXT-ONLY prompts',
    '> (`paint.mjs` without `--ref`) and describe the subject precisely; a job that needs a reference falls back to text.',
    '',
    `- Arena floors painted: ${floors.length ? floors.map(i => `layout ${i}`).join(', ') : 'none'} of 50 — \`arena-floors/floor-<id>.prompt.txt\` → \`painted/arena-floor-<id>.png\` → \`node tools/arena-floors/make-floors.mjs\``,
    `- Backdrop: ${files.includes('backdrop-highland.png') ? 'highland plain painted' : 'not painted'} — \`bg/highland.prompt.txt\` → \`node tools/bg-tile/make-tile.mjs <png> public/images/bg/highland-tile_768x768.webp --size 768 --hard\``,
    `- Prop sheets painted: ${props.length ? props.join(', ') : 'none'} — \`props/<sheet>.prompt.txt\` → \`painted/props-<sheet>.png\` → \`node tools/arena-props/pack.mjs\``,
    ''
  ]
}

export const writeStatus = (root = ROOT) => {
  const rows = bossPaintStatus(root)
  const cfg = loadConfig(root)
  const text = renderStatus(rows)
  writeFileSync(join(cfg.sheetsDir, STATUS_DOC), text, 'utf-8')
  return rows
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const rows = process.argv.includes('--print') ? bossPaintStatus(ROOT) : writeStatus(ROOT)
  for (const r of rows) {
    console.log(`${r.mark} ${r.needsPainting ? 'needs painting' : 'done          '}  ${r.stem.padEnd(24)} ${r.drawable ? r.shipped : ''}`)
  }
}
