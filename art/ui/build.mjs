#!/usr/bin/env node
/**
 * UI art (stat icons + power-up boxes) — export the reference sheets, the
 * master prompts and the desk's sheet index.
 *
 *   node art/ui/build.mjs
 *
 * 1. REFERENCES → art-sheets/ui/<stem>.png (painters.mjs, grey notation on
 *    magenta, on the set's exact lattice).
 * 2. art-sheets/PROMPTS-ui.md — one fenced block per set, headed
 *    `## title  (stem.png → first target)` for the desk's parser.
 * 3. art-sheets/sheet-index.json — MERGED: this file's sets replace their own
 *    entries, everything else is kept. It tells the desk every target a set
 *    cuts to (otherwise a job only knows its heading's one target).
 *
 * Nothing is baked: the game's drawn fallback is its own code, and the
 * runtime only requests files listed in src/data/uiArt.ts.
 */
import { chromium } from 'playwright'
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PROMPT_DOC, REFS_SUBDIR, SETS, SHEETS_DIR, finishRefs, setPrompt } from './manifest.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..', '..')
const refsDir = join(ROOT, SHEETS_DIR, REFS_SUBDIR)
mkdirSync(refsDir, { recursive: true })

const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage()
  page.on('pageerror', (e) => {
    console.error(`page error: ${e.message}`)
    process.exitCode = 1
  })
  await page.goto('about:blank')
  await page.addScriptTag({ type: 'module', content: readFileSync(join(HERE, 'painters.mjs'), 'utf-8') })
  await page.waitForFunction(() => window.UI_ART_PAINTERS)
  for (const set of SETS) {
    const b64 = await page.evaluate((set) => {
      const c = document.createElement('canvas')
      c.width = set.sheet.w
      c.height = set.sheet.h
      window.UI_ART_PAINTERS.sheet(c.getContext('2d'), set)
      return c.toDataURL('image/png').split(',')[1]
    }, set)
    writeFileSync(join(refsDir, `${set.stem}.png`), Buffer.from(b64, 'base64'))
  }
  console.log(`refs      ${SETS.length} → ${SHEETS_DIR}/${REFS_SUBDIR}/`)
} finally {
  await browser.close()
}

// prompts
const fenceFor = (body) => '`'.repeat(Math.max(3, Math.max(0, ...(body.match(/`+/g) ?? []).map((r) => r.length)) + 1))
const md = [
  '# UI art prompts — Chaos Arena (generated by art/ui/build.mjs — do not edit by hand)',
  '',
  'The stat icons (team upgrade screen, in-battle stat cards, power-up boxes) and the power-up boxes.',
  'Until a set is painted the game draws its own fallback (the SVG stat icons, renderPowerup).',
  'Paint the STAT ICONS first: the power-up box prompt attaches the painted icon sheet as a finish reference.',
  '',
  'Paint: attach the finish references listed under a heading FIRST, the layout reference LAST, then paste ONLY the fenced block.',
  'Or `pnpm art:desk` → search the sprite name → Copy image, then prompt. Returns are sliced by art/ui/slice-return.mjs.',
  ''
]
for (const set of SETS) {
  const prompt = setPrompt(set)
  const first = set.cells.find(Boolean)
  md.push(`## ${set.title}  (${set.stem}.png → ${first.target})`, '')
  md.push(`Attach, in this order: ${finishRefs(set).map((f) => `\`${f}\``).join(', ')}, then \`${SHEETS_DIR}/${REFS_SUBDIR}/${set.stem}.png\` LAST.`, '')
  md.push(`${fenceFor(prompt)}text`, prompt.trimEnd(), fenceFor(prompt), '')
}
writeFileSync(join(ROOT, SHEETS_DIR, PROMPT_DOC), md.join('\n'), 'utf-8')
console.log(`prompts   ${SHEETS_DIR}/${PROMPT_DOC} (${SETS.length} jobs)`)

// sheet index (merge, atomic)
const indexFile = join(ROOT, SHEETS_DIR, 'sheet-index.json')
const index = existsSync(indexFile) ? JSON.parse(readFileSync(indexFile, 'utf-8')) : {}
const mine = new Set(SETS.map((s) => `${REFS_SUBDIR}/${s.stem}.png`))
index.sheets = [
  ...(index.sheets ?? []).filter((s) => !mine.has(s.files?.clean)),
  ...SETS.map((s) => ({
    files: { clean: `${REFS_SUBDIR}/${s.stem}.png` },
    grid: s.grid,
    cells: s.cells.filter(Boolean)
  }))
]
writeFileSync(`${indexFile}.tmp`, `${JSON.stringify(index, null, 2)}\n`, 'utf-8')
renameSync(`${indexFile}.tmp`, indexFile)
console.log(`index     ${SHEETS_DIR}/sheet-index.json (${SETS.length} sets merged)`)
